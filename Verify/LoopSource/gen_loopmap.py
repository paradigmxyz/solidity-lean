#!/usr/bin/env python3
"""Turn solar-verify's loop-head manifest into a Lean LoopMap, after checking its pins.

Usage: gen_loopmap.py HEADS.json MANIFEST.json SOURCE.sol OBLIGATIONS.lean NAMESPACE OUT.lean

HEADS.json is what solar-verify --emit-loop-heads writes (format "solar-verify loop heads 1");
MANIFEST.json the --emit-lean manifest of the obligations, OBLIGATIONS.lean their Lean module
(gen_loopvc.py). Each loop-head variable gives places for its SSA names:

  head {ssa}  of a storage var: slot s at the head      (Loc.slot s)
              of a local, param or return: the name x   (Loc.var x, in scope at the head)
  entry {ssa} of a storage var: slot s at the call's start (Loc.entrySlot s)
              of a param: the same name x               (Loc.var x; a param the loop leaves alone)

Names the obligations use that no head variable places (the loop-free state, such as a storage
variable the loop does not mention, and the call environment: this, msg.sender, msg.value) are
listed as freeNames: the binding supplies their values, and the obligations' facts are still
checked at them.

Exit 3, writing nothing, when the manifest is stale or does not fit: another format or compiler
than the obligations', another source hash (recomputed from SOURCE.sol), dry_run or strict, no
entry for the obligations' function, other than one loop, or a kind or place this consumer does not
know. Run solar-verify --check-loop-heads first to reject a manifest the source no longer gives. A
manifest that passes but places a name wrongly is rejected by the Lean binding, whose word lemmas
(M.word headerS x = some w, by decide) then fail.
"""
import hashlib
import json
import re
import sys

BT = chr(96)


def blocked(msg):
    print(f"REJECTED: {msg}", file=sys.stderr)
    sys.exit(3)


def code(s):
    return BT + str(s) + BT


def main(argv):
    hp, man, src, obl, ns, out = argv
    h = json.load(open(hp))
    f = json.load(open(man))
    if h.get("format") != "solar-verify loop heads 1":
        blocked(f"format {h.get('format')!r}")
    if h.get("compiler") != f["compiler"]:
        blocked(f"compiler {h.get('compiler')!r} != obligations' {f['compiler']!r}")
    for k in ("dry_run", "strict"):
        if h.get("options", {}).get(k) != f["options"].get(k):
            blocked(f"option {k}: {h.get('options', {}).get(k)!r} != obligations' {f['options'].get(k)!r}")
    if h["options"].get("only") not in (None, f["options"]["only"]):
        blocked(f"heads for {h['options']['only']!r}, obligations for {f['options']['only']!r}")
    real = hashlib.sha256(open(src, "rb").read()).hexdigest()
    fsrc = {s["path"]: s["sha256"] for s in f["sources"]}
    hs = h.get("source", {})
    if fsrc.get(hs.get("path")) != hs.get("sha256"):
        blocked(f"source {hs} not the obligations' {fsrc}")
    if real != hs.get("sha256"):
        blocked(f"{src} hashes to {real}, not {hs.get('sha256')}")
    (unit,) = f["units"]
    fns = [g for g in h["functions"] if g["function"] == unit["name"]]
    if len(fns) != 1:
        blocked(f"no single entry for {unit['name']}")
    (fn,) = fns
    if len(fn["loops"]) != 1:
        blocked(f"{unit['name']} has {len(fn['loops'])} loops; this consumer takes one")
    (loop,) = fn["loops"]
    places = {}

    def put(x, lean):
        if x in places and places[x] != lean:
            blocked(f"{x} placed twice: {places[x]} and {lean}")
        places[x] = lean

    for v in loop["vars"]:
        kind = v["kind"]
        if kind == "storage":
            if v.get("offset", 0) != 0 or v.get("type") != "t_uint256":
                blocked(f"storage {v['name']}: only full-word t_uint256 slots are taken")
            s = int(v["slot"])
            if "ssa" in v["head"]:
                put(v["head"]["ssa"], f".slot {s}")
            if "ssa" in v["entry"]:
                put(v["entry"]["ssa"], f".entrySlot {s}")
        elif kind in ("local", "param", "return"):
            if "ssa" in v["head"]:
                put(v["head"]["ssa"], f".var {json.dumps(v['name'])}")
            if kind == "param" and "ssa" in v["entry"]:
                if v["havocked"]:
                    blocked(f"param {v['name']} written by the loop: its entry value has no place")
                put(v["entry"]["ssa"], f".var {json.dumps(v['name'])}")
        else:
            blocked(f"kind {kind!r} of {v['name']}")
    used = sorted(set(re.findall(r'\.ivar "([^"]+)"', open(obl).read())))
    free = [x for x in used if x not in places]
    hsha = hashlib.sha256(open(hp, "rb").read()).hexdigest()
    locs = [f"  ({json.dumps(x)}, {places[x]})" for x in sorted(places)]
    lines = [
        "-- Generated by Verify/LoopSource/gen_loopmap.py; do not edit.",
        "import Verify.LoopSource.LoopMap",
        "",
        "/-!",
        f"# The loop-head map of {unit['name']} (loop at line {loop['line']}, column {loop['column']})",
        "",
        f"From {code(hp.split('/')[-1])} (sha256 {code(hsha)}), emitted by solar-verify",
        f"{code('--emit-loop-heads')}, compiler {code(h['compiler'])}, source {code(hs['path'])}",
        f"{code(hs['sha256'])}, checked against the obligations' manifest (script {code(f['lean']['smt_sha256'])}).",
        "-/",
        "",
        f"namespace {ns}",
        "",
        "open SolidCore.Verify.LoopMap",
        "",
        "/-- The places the loop-head manifest gives solar-verify's SSA names. -/",
        "def M : LoopMap := ⟨[",
        ",\n".join(locs) + "]⟩",
        "",
        "/-- Names the obligations use that no loop-head variable places: the binding supplies them. -/",
        "def freeNames : List String := [" + ", ".join(json.dumps(x) for x in free) + "]",
        "",
        "/-- sha256 of the loop-head manifest. -/",
        f'def headsSha256 : String := "{hsha}"',
        "",
        f"end {ns}",
        "",
    ]
    open(out, "w").write("\n".join(lines))
    print(json.dumps({"out": out, "heads_sha256": hsha, "placed": sorted(places), "free": free}))


if __name__ == "__main__":
    main(sys.argv[1:])
