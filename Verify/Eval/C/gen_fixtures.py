#!/usr/bin/env python3
"""Generate lane C's EVM scaling fixtures: NatCode programs of N opcodes.

Kinds (every program ends in PUSH1 0, PUSH1 0, REVERT, and every statement is
Spec .fusaka (At code msg 0 [x, y] .empty 10000000 st ss .empty) Reverted):

* Straight: PUSH1 ADD SWAP1 PUSH1 XOR SWAP1 DUP2 POP, repeated; every word is used once.
* Shared: DUP1 PUSH1 ADD ADD, repeated; the top word appears twice in the next one, so the frame is
  a DAG whose tree size doubles every 4 opcodes.
* Branch: blocks of CALLVALUE PUSH2 r JUMPI (decided by the hypothesis msg.value = 0) and
  PUSH1 off CALLDATALOAD PUSH2 r JUMPI (a genuine split on a call-data word), in the ratio 2:1;
  every taken jump goes to one shared JUMPDEST PUSH1 0 PUSH1 0 REVERT block.
* BranchNeg (negative, one size): Branch whose fall-through end is STOP instead of REVERT: the
  statement is false on exactly that one path, which carries the zero path condition of every
  split; the stepper must leave exactly it open (no sibling's nonzero condition may refute it).

For each kind and N it writes Fix/<Kind><N>Stmt.lean (the statement, once), Fix/<Kind><N>Base.lean
(baseline: EthLib evm_step, or Symex symex_one for branches) and Fix/<Kind><N>Sym.lean (evm_sym).
"""
import pathlib, sys

ROOT = pathlib.Path(__file__).parent / "Fix"
SIZES = [16, 32, 64, 128, 256]

PUSH1, PUSH2, ADD, XOR, SWAP1, DUP1, DUP2, POP = 0x60, 0x61, 0x01, 0x18, 0x90, 0x80, 0x81, 0x50
JUMPDEST, JUMPI, CALLVALUE, CALLDATALOAD, REVERT, STOP = 0x5b, 0x57, 0x34, 0x35, 0xfd, 0x00
TAIL = [(PUSH1, 0), (PUSH1, 0), (REVERT,)]

def assemble(ops):
    out = []
    for op in ops:
        out.append(op[0])
        if op[0] == PUSH1: out.append(op[1] & 0xff)
        if op[0] == PUSH2: out += [(op[1] >> 8) & 0xff, op[1] & 0xff]
    return out

def straight(n):
    cyc = [(PUSH1, 7), (ADD,), (SWAP1,), (PUSH1, 0x5a), (XOR,), (SWAP1,), (DUP2,), (POP,)]
    body = []
    while len(body) + len(cyc) <= n - len(TAIL): body += cyc
    body += [(JUMPDEST,)] * (n - len(TAIL) - len(body))
    return body + TAIL, False

def shared(n):
    cyc = [(DUP1,), (PUSH1, 3), (ADD,), (ADD,)]
    body = []
    while len(body) + len(cyc) <= n - len(TAIL): body += cyc
    body += [(JUMPDEST,)] * (n - len(TAIL) - len(body))
    return body + TAIL, False

def branch(n, neg=False):
    # layout: blocks, pad, end, revert block (4 ops)
    end = [(STOP,)] if neg else TAIL
    room = n - len(end) - 4
    blocks, k, off = [], 0, 4
    while True:
        b = "split" if k % 3 == 2 else "dec"
        size = 4 if b == "split" else 3
        if sum(4 if x[0] == "split" else 3 for x in blocks) + size > room: break
        blocks.append((b, off)); k += 1
        if b == "split": off = (off + 32) % 224
    used = sum(4 if x[0] == "split" else 3 for x in blocks)
    pad = room - used
    # byte offset of the revert block
    def body(r):
        ops = []
        for b, o in blocks:
            if b == "dec": ops += [(CALLVALUE,), (PUSH2, r), (JUMPI,)]
            else: ops += [(PUSH1, o), (CALLDATALOAD,), (PUSH2, r), (JUMPI,)]
        return ops + [(JUMPDEST,)] * pad + end
    r = len(assemble(body(0)))
    ops = body(r) + [(JUMPDEST,), (PUSH1, 0), (PUSH1, 0), (REVERT,)]
    assert len(ops) == n, (len(ops), n)
    return ops, True

KINDS = {"Straight": straight, "Shared": shared, "Branch": branch}

def stmt_file(kind, n, ops, hyp):
    code = assemble(ops)
    num = int.from_bytes(bytes(code), "big")
    h = "msg.value = 0 →\n    " if hyp else ""
    return f'''import SolidCore.Refinement.Evm.Symex

/-! Lane C fixture {kind}{n}: {n} opcodes, {len(code)} bytes. Generated by gen_fixtures.py. -/

open EthLib.Base EthLib.Execution EthLib.Execution.Evm EthLib.Execution.Evm.Logic
open SolidCore.Refinement.Evm.Symex

namespace Verify.Eval.C.Fix.{kind}{n}

def codeNat : Nat := 0x{num:0{2 * len(code)}x}

def codeSize : Nat := {len(code)}

def stmt : Prop :=
  ∀ (msg : Message .fusaka) (st : State.TransactionState) (ss : Substate) (x y : U256),
    {h}Spec .fusaka (At (NatCode.ofNat codeNat codeSize) msg 0 [x, y] .empty 10000000 st ss .empty)
      Reverted

end Verify.Eval.C.Fix.{kind}{n}
'''

def base_file(kind, n, hyp):
    ns = f"Verify.Eval.C.Fix.{kind}{n}"
    if hyp:
        proof = '''  unfold stmt
  intro msg st ss x y hv
  have hfork : Fork.fusaka ≤ Fork.fusaka := by decide
  all_goals repeat symex_one [codeNat, codeSize] [hv] hfork'''
    else:
        proof = '''  unfold stmt
  intro msg st ss x y
  repeat evm_step [codeNat, codeSize]
  refine revert_empty (by decide) ?_ ?_ <;> evm_code [codeNat, codeSize]'''
    return f'''import Verify.Eval.C.Fix.{kind}{n}Stmt
import Verify.Eval.Common.Measure

open EthLib.Base EthLib.Execution EthLib.Execution.Evm EthLib.Execution.Evm.Logic GasCosts
open SolidCore.Refinement.Evm.Logic SolidCore.Refinement.Evm.Symex

namespace {ns}

set_option maxRecDepth 100000
set_option maxHeartbeats 0

theorem base : stmt := by
{proof}

#proof_stats base
#kernel_recheck base

end {ns}
'''

def sym_file(kind, n):
    ns = f"Verify.Eval.C.Fix.{kind}{n}"
    return f'''import Verify.Eval.C.Fix.{kind}{n}Stmt
import Verify.Eval.C.Stepper
import Verify.Eval.Common.Measure

namespace {ns}

set_option maxRecDepth 100000
set_option maxHeartbeats 0

theorem sym : stmt := by
  unfold stmt
  evm_sym [codeNat, codeSize]

#proof_stats sym
#kernel_recheck sym

end {ns}
'''

def main():
    ROOT.mkdir(exist_ok=True)
    for kind, f in KINDS.items():
        for n in SIZES:
            ops, hyp = f(n)
            (ROOT / f"{kind}{n}Stmt.lean").write_text(stmt_file(kind, n, ops, hyp))
            (ROOT / f"{kind}{n}Base.lean").write_text(base_file(kind, n, hyp))
            (ROOT / f"{kind}{n}Sym.lean").write_text(sym_file(kind, n))
    ops, hyp = branch(64, neg=True)
    (ROOT / "BranchNeg64Stmt.lean").write_text(stmt_file("BranchNeg", 64, ops, hyp))

if __name__ == "__main__":
    main()
