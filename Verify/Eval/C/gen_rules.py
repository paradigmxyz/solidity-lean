out = [HEAD.replace("BT", chr(96))]

# PUSH1..PUSH32
for k in range(1, 33):
    out.append(f'''theorem step_push{k} (hlt : pc + {k} < size)
    (hb : n >>> (8 * (size - 1 - pc)) % 256 = {0x5f + k}) (hgas : 3 ≤ gas)
    (hroom : stack.length < 1024)
    (next : Hoare .fusaka (At (ofNat n size) msg (pc + {1 + k})
      (BitVec.ofNat 256 (n >>> (8 * (size - 1 - (pc + {k}))) % {256 ** k}) :: stack) mem (gas - 3)
      st ss rd) R) :
    Hoare .fusaka (At (ofNat n size) msg pc stack mem gas st ss rd) R :=
  step_pushN ⟨{k}, by decide⟩ (by decide) (by decide) hlt hb hgas hroom next
''')

BIN = [  # name, byte, op, result expression in x y, rewrite
    ("add", 0x01, ".add", "x + y", None),
    ("sub", 0x03, ".sub", "x - y", None),
    ("lt", 0x10, ".lt", "(if x < y then 1 else 0)", "lessThan_eq"),
    ("gt", 0x11, ".gt", "(if y < x then 1 else 0)", "greaterThan_eq"),
    ("eq", 0x14, ".eq", "(if x = y then 1 else 0)", None),
    ("and", 0x16, ".and", "x &&& y", None),
    ("or", 0x17, ".or", "x ||| y", None),
    ("xor", 0x18, ".xor", "x ^^^ y", None),
    ("shl", 0x1b, ".shl", "(if x.toNat < 256 then y <<< x.toNat else 0)", None),
    ("shr", 0x1c, ".shr", "(if x.toNat < 256 then y >>> x.toNat else 0)", None),
]
FN = {"add": "add", "mul": "mul", "sub": "sub", "lt": "lessThan", "gt": "greaterThan",
      "eq": "equal", "and": "bitwiseAnd", "or": "bitwiseOr", "xor": "bitwiseXor",
      "shl": "bitwiseShl", "shr": "bitwiseShr"}
for name, byte, op, res, rw in BIN:
    if rw:
        nxt = f"(by rw [{rw}]; exact next)"
    else:
        nxt = "next"
    out.append(f'''theorem step_{name} {{x y : U256}} {{rest : List U256}} (hlt : pc < size)
    (hb : n >>> (8 * (size - 1 - pc)) % 256 = {byte}) (hgas : 3 ≤ gas)
    (next : Hoare .fusaka (At (ofNat n size) msg (pc + 1) (({res}) :: rest) mem (gas - 3) st ss rd)
      R) :
    Hoare .fusaka (At (ofNat n size) msg pc (x :: y :: rest) mem gas st ss rd) R :=
  binary_of (f := {FN[name]}) (byte := {byte}) (op := {op}) (by decide) (by decide) rfl hlt hb hgas
    {nxt}
''')

UN = [("iszero", 0x15, ".iszero", "(if x = 0 then 1 else 0)", "isZero"),
      ("not", 0x19, ".not", "~~~x", "bitwiseNot")]
for name, byte, op, res, fn in UN:
    out.append(f'''theorem step_{name} {{x : U256}} {{rest : List U256}} (hlt : pc < size)
    (hb : n >>> (8 * (size - 1 - pc)) % 256 = {byte}) (hgas : 3 ≤ gas)
    (next : Hoare .fusaka (At (ofNat n size) msg (pc + 1) (({res}) :: rest) mem (gas - 3) st ss rd)
      R) :
    Hoare .fusaka (At (ofNat n size) msg pc (x :: rest) mem gas st ss rd) R :=
  unary_of (f := {fn}) (byte := {byte}) (op := {op}) (by decide) (by decide) rfl hlt hb hgas next
''')

# DUP1..DUP8, SWAP1..SWAP8 with explicit stacks
for k in range(1, 9):
    xs = [f"x{i}" for i in range(1, k + 1)]
    st_ = " :: ".join(xs) + " :: rest"
    out.append(f'''theorem step_dup{k} {{{" ".join(xs)} : U256}} {{rest : List U256}} (hlt : pc < size)
    (hb : n >>> (8 * (size - 1 - pc)) % 256 = {0x7f + k}) (hgas : 3 ≤ gas)
    (hroom : ({st_}).length < 1024)
    (next : Hoare .fusaka (At (ofNat n size) msg (pc + 1) (x{k} :: {st_}) mem (gas - 3) st ss rd)
      R) :
    Hoare .fusaka (At (ofNat n size) msg pc ({st_}) mem gas st ss rd) R :=
  step_of (fun h hc => dup_of_decode (n := ⟨{k - 1}, by decide⟩) h hc (by decide) rfl hgas hroom)
    hlt hb next
''')
for k in range(1, 9):
    xs = [f"x{i}" for i in range(1, k + 1)]
    src = "t :: " + " :: ".join(xs) + " :: rest"
    dst = " :: ".join([f"x{k}"] + xs[:-1] + ["t"]) + " :: rest"
    out.append(f'''theorem step_swap{k} {{t {" ".join(xs)} : U256}} {{rest : List U256}} (hlt : pc < size)
    (hb : n >>> (8 * (size - 1 - pc)) % 256 = {0x8f + k}) (hgas : 3 ≤ gas)
    (next : Hoare .fusaka (At (ofNat n size) msg (pc + 1) ({dst}) mem (gas - 3) st ss rd) R) :
    Hoare .fusaka (At (ofNat n size) msg pc ({src}) mem gas st ss rd) R :=
  step_of (fun h hc => swap_of_decode (n := ⟨{k - 1}, by decide⟩) h hc (by decide) rfl hgas)
    hlt hb next
''')

out.append("end Verify.Eval.C\n")
pathlib.Path(__file__).with_name("Rules.lean").write_text("\n".join(out))
