#!/usr/bin/env python3
r"""Lane G: the real side conditions captured from W1Proofs' sym_mem (capture.sh) as standalone
Lean statements, one theorem per path context, each running g_compare (Bench.lean) on the
candidate side conditions in the order sym_mem asked them, repeats included.

usage: gen_real.py CAPTURE.txt OUT.lean NAME
"""
import re, sys

src, out, name = sys.argv[1:4]
s = open(src).read()
caps = re.findall(r"CAPTURE ok=(\w+) ms=([0-9.]+)\n(.*?)\nENDCAPTURE", s, re.S)
groups = {}
for ok, ms, t in caps:
    head, _, goal = t.rpartition(" :\n")
    groups.setdefault(head, []).append((ok, float(ms), " ".join(goal.split())))
with open(out, "w") as f:
    f.write("import W1Proofs.Tactic\nimport Verify.Eval.G.Bench\n\n")
    f.write(f"/-! Lane G: the side conditions W1Proofs' sym_mem_disch was asked in {name}'s stage proofs,\n")
    f.write("verbatim as captured (Capture/Hook.lean, printed with full names and numeric types), one\n")
    f.write("theorem per path context with the candidates in the order they were asked. Generated by\n")
    f.write("gen_real.py; the base is the repository's own sym_mem_disch. -/\n\n")
    f.write("set_option linter.unusedVariables false\nset_option maxHeartbeats 0\nset_option maxRecDepth 100000\n\n")
    for k, (head, items) in enumerate(groups.items()):
        oks = sum(1 for o, _, _ in items if o == "true")
        tot = sum(m for _, m, _ in items)
        binders = head.replace("theorem CAPNAME", "").strip()
        f.write(f"/-- {len(items)} candidates, {oks} proved by sym_mem_disch at capture ({tot:.1f} ms there). -/\n")
        f.write(f"theorem real_{k} {binders} :\n    True := by\n  g_compare [\n")
        f.write(",\n".join("    " + g for _, _, g in items))
        f.write("] base sym_mem_disch\n  trivial\n\n")
print(len(caps), "captures,", len(groups), "contexts")
