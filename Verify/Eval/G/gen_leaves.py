#!/usr/bin/env python3
r"""Lane G: the leaves of Contracts/VerifyCounter/Bump.lean's generated loop proof (captured by
Capture/BumpLeaves.lean) as standalone theorems, each proved three ways on the identical
statement:

  old     Bump.lean's own total_leaf (bv_omega / sym_omega leaves)
  grind   total_leaf's structure with every bv_omega / sym_omega closer replaced by
          grind [EvmRules.Evm.add] (the one word operation the leaves mention, as the only extra lemma)
  shared  total_leaf's structure, where the leaf's arithmetic subgoals are closed together by
          g_close_all: one grind fact state for the leaf's context, internalized once
          (Shared.lean's factsAt), and one discharge per subgoal

The leaf total_leaf could not close at capture (the growing rank of BumpWrongRank.lean) is the
negative: every variant must fail on it (fail_if_success).

usage: gen_leaves.py CAPTURE.txt OUT.lean
"""
import re, sys

src, out = sys.argv[1:3]
s = open(src).read()
leaves = re.findall(r"LEAF ok=(\w+) ms=([0-9.]+)\n(.*?)\nENDLEAF", s, re.S)

HEADER = '''import Contracts.VerifyCounter.Bump
import Verify.Eval.G.Shared
import Verify.Eval.G.Kernel

/-! Lane G: the leaves of bump's generated loop proof (Contracts/VerifyCounter/Bump.lean, with the
invariant solar generated into Inferred.lean), verbatim as captured by Capture/BumpLeaves.lean,
each proved by Bump.lean's total_leaf (old), by the same structure with grind in place of
bv_omega/sym_omega (grind), and with the arithmetic subgoals of a leaf closed from one shared grind
fact state (shared). Generated by gen_leaves.py. -/

set_option linter.unusedVariables false
set_option maxHeartbeats 4000000
set_option maxRecDepth 100000

/-- BumpWrongRank.lean's growing rank, verbatim (the leaves of its back-edge run mention it). -/
def SolarTV.Milestone.VerifyCounter.Bump.growing_g (x : SolarTV.MIR.Lowered.Frame) : Nat := (x.2.2.1 20).toNat

namespace Verify.Eval.G.BumpLeaves

open SolarTV.Milestone.VerifyCounter.Bump
open SolarTV.Machine SolarTV.Export.Counter SolarTV.Milestone.W1
open SolarTV.CutPoint (seg SegEnds)

open Lean Meta Elab Tactic in
/-- Closes every open goal from one grind fact state per local context (Shared.lean's factsAt and
Facts.discharger), with no trigger lemma: the goals' hypotheses are internalized once. Fails if
any goal is left. -/
elab "g_close_all" : tactic => do
  let goals ← getUnsolvedGoals
  if goals.isEmpty then return
  let params ← Verify.Eval.G.sideParams #[]
  let ok ← Grind.GrindM.run (params := params) do
    let mut facts : Option (MVarId × Verify.Eval.G.Facts) := none
    for g in goals do
      let f ← match facts with
        | some (g0, f) =>
          if (← g0.getDecl).lctx.decls.size == (← g.getDecl).lctx.decls.size &&
              (← g0.getDecl).lctx.getFVarIds == (← g.getDecl).lctx.getFVarIds then pure f
          else Verify.Eval.G.factsAt params none g
        | none => Verify.Eval.G.factsAt params none g
      facts := some (g, f)
      let d ← f.discharger
      let ty ← g.withContext do instantiateMVars (← g.getType)
      let (r, _) ← g.withContext <| Sym.Simp.SimpM.run (d ty)
      match r with
      | .solved pf _ => g.assign pf
      | .failed _ => return false
    return true
  unless ok do throwError "g_close_all: a goal is left"
  replaceMainGoal []

macro "word_goal_g" : tactic => `(tactic| (
  first
    | rfl
    | (intro k hk; simp only [update, hk, ↓reduceIte])
    | (simp only [update, MIR.Lowered.Env.set, ↓reduceIte, Nat.reduceEqDiff, EvmRules.Evm.add, *]; done)
    | (simp only [update, MIR.Lowered.Env.set, ↓reduceIte, Nat.reduceEqDiff, EvmRules.Evm.add, *]; grind [EvmRules.Evm.add])
    | grind [EvmRules.Evm.add]))

macro "mem_goal_g" : tactic => `(tactic| (
  first
    | (simp only [load_128_store_160, load_160_store_128, Mem.load_store_same, Mem.load_expand,
        MIR.Lowered.Env.set, ↓reduceIte, Nat.reduceEqDiff, EvmRules.Evm.add, *]; done)
    | word_goal_g))

macro "rank_goal_g" : tactic => `(tactic| (
  simp only [Inferred.rank, MIR.Lowered.Env.set, ↓reduceIte, Nat.reduceEqDiff, EvmRules.Evm.add, *] <;> grind [EvmRules.Evm.add]))

macro "inv_goal_g" : tactic => `(tactic| (
  first
    | (unfold Inferred.Inv; refine Or.inl ⟨_, _, rfl, ?_⟩; unfold Inferred.at7;
        (try simp only [EvmRules.Evm.add] at *); and_intros <;> mem_goal_g)
    | (unfold Inferred.Inv; refine Or.inr ⟨_, _, rfl, ?_⟩; unfold Inferred.at10;
        (try simp only [EvmRules.Evm.add] at *); and_intros <;> mem_goal_g)))

/-- total_leaf with grind in place of bv_omega and sym_omega. -/
macro "total_leaf_g" : tactic => `(tactic| (
  first
    | (unfold Post; dsimp only; intro h; rcases h with h | ⟨_, h⟩ <;> exact Halt.noConfusion h)
    | (unfold Post; dsimp only; intro _; (try simp only [EvmRules.Evm.add] at *);
        refine ⟨?_, ?_, ?_, ?_⟩ <;> word_goal_g)
    | (refine ⟨?_, ?_⟩
       · inv_goal_g
       · first | exact True.intro | rank_goal_g)
    | inv_goal_g
    | (exfalso; grind [EvmRules.Evm.add])))

/-- The cheap closers of word_goal and mem_goal on each subgoal, then every arithmetic subgoal
left closed together from one shared grind fact state. -/
macro "cheap_then_shared" : tactic => `(tactic| (
  all_goals try first
    | rfl
    | (intro k hk; simp only [update, hk, ↓reduceIte]; done)
    | (simp only [load_128_store_160, load_160_store_128, Mem.load_store_same, Mem.load_expand,
        update, MIR.Lowered.Env.set, ↓reduceIte, Nat.reduceEqDiff, EvmRules.Evm.add, *]; done)
  all_goals try simp only [load_128_store_160, load_160_store_128, Mem.load_store_same,
    Mem.load_expand, update, MIR.Lowered.Env.set, ↓reduceIte, Nat.reduceEqDiff, EvmRules.Evm.add,
    Inferred.rank]
  all_goals try simp only [EvmRules.Evm.add] at *
  g_close_all))

/-- total_leaf where a leaf's arithmetic subgoals share one grind fact state. -/
macro "total_leaf_s" : tactic => `(tactic| (
  first
    | (unfold Post; dsimp only; intro h; rcases h with h | ⟨_, h⟩ <;> exact Halt.noConfusion h)
    | (unfold Post; dsimp only; intro _; (try simp only [EvmRules.Evm.add] at *);
        refine ⟨?_, ?_, ?_, ?_⟩; cheap_then_shared)
    | (unfold Inferred.Inv; refine ⟨Or.inl ⟨_, _, rfl, ?_⟩, ?_⟩; unfold Inferred.at7;
        (try simp only [EvmRules.Evm.add] at *); and_intros; cheap_then_shared)
    | (unfold Inferred.Inv; refine ⟨Or.inr ⟨_, _, rfl, ?_⟩, ?_⟩; unfold Inferred.at10;
        (try simp only [EvmRules.Evm.add] at *); and_intros; cheap_then_shared)
    | (unfold Inferred.Inv; refine Or.inl ⟨_, _, rfl, ?_⟩; unfold Inferred.at7;
        (try simp only [EvmRules.Evm.add] at *); and_intros; cheap_then_shared)
    | (unfold Inferred.Inv; refine Or.inr ⟨_, _, rfl, ?_⟩; unfold Inferred.at10;
        (try simp only [EvmRules.Evm.add] at *); and_intros; cheap_then_shared)
    | (exfalso; (try simp only [EvmRules.Evm.add] at *); g_close_all)))
'''

with open(out, "w") as f:
    f.write(HEADER)
    neg = 0
    for k, (ok, ms, t) in enumerate(leaves):
        head, _, goal = t.rpartition(" :\n")
        binders = head.replace("theorem CAPNAME", "").strip()
        variants = [("old", "total_leaf"), ("grind", "total_leaf_g"), ("shared", "total_leaf_s")]
        if ok == "true":
            f.write(f"\n-- Leaf {k}: total_leaf closed it at capture in {float(ms):.1f} ms.\n")
            for v, tac in variants:
                f.write(f'g_time "leaf{k} {v}" in\ntheorem leaf{k}_{v} {binders} :\n    {goal} := by\n  {tac}\n')
                f.write(f"#kernel_recheck_all leaf{k}_{v}\n#proof_stats leaf{k}_{v}\n#print axioms leaf{k}_{v}\n")
        else:
            neg += 1
            f.write(f"\n-- Leaf {k}: the negative (total_leaf failed at capture); every variant must fail.\n")
            f.write(f"def neg{k} : Prop :=\n  ∀ {binders},\n    {goal}\n")
            for v, tac in variants:
                f.write(f"example : True := by\n  fail_if_success\n    have : neg{k} := by\n      unfold neg{k}; intros\n      {tac}\n  trivial\n")
    f.write("\nend Verify.Eval.G.BumpLeaves\n")
print(len(leaves), "leaves,", neg, "negative")
