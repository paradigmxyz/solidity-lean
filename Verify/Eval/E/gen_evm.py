#!/usr/bin/env python3
"""Lane E EVM fixtures (docs/eval/e.md): the join and chain programs of gen.py, as NatCode
bytecode stepped by EthLib's own evm_step / evm_stop (Logic/Steps.lean).

  python3 Verify/Eval/E/gen_evm.py <outdir>

join (P=4 paths, dispatcher DUP1 PUSH1 i EQ PUSH1 A_i JUMPI, blocks A_i, shared block B):
  inline    every path's conjunct steps its whole run with evm_step, B included
  shared    B is one lemma blockB, general in its two stack words and its gas
  perblock  every A_i and B is a lemma
chain (N opcodes PUSH1 k ADD SWAP1 ..., STOP; 8-opcode blocks):
  mono, linLit, balLit, linDef, balDef as in gen.py
Every variant of one family and size proves the same theorem main.
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen import join_prog, chain_prog, assemble, nat, ops_of, block_ops, cost, COST, P, BLK, tree

G0 = 10000000
CODE = '[code, codeNat]'
Q = '(fun e => ∃ g, Halted false .empty g st ss e)'
BIND = '{fork : Fork} (message : Message fork) (st : State.TransactionState) (ss : Substate)'

def header(ns, bs, extra=''):
    return ('import EthLib.Execution.Proofs.Evm.Logic.Steps\nimport Verify.Eval.E.Stats\n\n'
            '-- Generated by Verify/Eval/E/gen_evm.py. Do not edit.\n\n'
            'set_option maxHeartbeats 0\nset_option maxRecDepth 100000\n\n'
            'open EthLib.Base EthLib.Execution EthLib.Execution.Evm EthLib.Execution.Evm.Logic\n\n'
            'namespace %s\n\n'
            '/-- A stop with any gas left. -/\n'
            'theorem close {fork : Fork} {code : ByteArray} {message : Message fork} {pc : Nat}\n'
            '    {stk : List U256} {gas : Nat} {st : State.TransactionState} {ss : Substate}\n'
            '    (h : Spec fork (At code message pc stk .empty gas st ss .empty) (Halted false .empty gas st ss)) :\n'
            '    Spec fork (At code message pc stk .empty gas st ss .empty)\n'
            '      (fun e => ∃ g, Halted false .empty g st ss e) :=\n'
            '  Spec.consequence h (fun _ h => h) (fun _ h => ⟨_, h⟩)\n\n'
            'def codeNat : Nat := %s\ndef code : ByteArray := NatCode.ofNat codeNat %d\n\n%s'
            % (ns, nat(bs), len(bs), extra))

def footer(ns):
    return '\n#e_stats %s\n#kernel_recheck %s.main\n\nend %s\n' % (ns, ns, ns)

STOP = ('  refine close ?_\n'
        '  evm_stop %s' % CODE)

def steps(n, indent='  '):
    return [indent + 'evm_step %s' % CODE] * n

def at(pc, stk, gas):
    return '(At code message %d [%s] .empty %s st ss .empty)' % (pc, ', '.join(stk), gas)

def write(outdir, name, src):
    with open(os.path.join(outdir, name + '.lean'), 'w') as f: f.write(src)

def gen_join(N, variant, outdir):
    prog = join_prog(N); bs, labels = assemble(prog)
    ns = 'Verify.Eval.E.Evm.Join%d_%s' % (N, variant)
    pcB = labels['B']; Bops = block_ops(prog, 'B'); costB = cost(Bops)
    extra = ''
    if variant in ('shared', 'perblock'):
        extra += ('theorem blockB %s (a b : U256) (g : Nat) (hg : %d ≤ g) :\n    Spec fork %s %s := by\n'
                  % (BIND, costB + 10, at(pcB, ['a', 'b'], 'g'), Q))
        extra += '\n'.join(steps(len(Bops) - 1)) + '\n' + STOP + '\n\n'
    if variant == 'perblock':
        for i in range(P):
            Aops = block_ops(prog, 'A%d' % i)
            extra += ('theorem blockA%d %s (a b : U256) (g : Nat) (hg : %d ≤ g) :\n    Spec fork %s %s := by\n'
                      % (i, BIND, cost(Aops) + costB + 10, at(labels['A%d' % i], ['a', 'b'], 'g'), Q))
            extra += '\n'.join(steps(len(Aops))) + '\n  exact blockB message st ss _ _ _ (by omega)\n\n'
    conj = ' ∧\n      '.join('Spec fork %s %s' % (at(0, ['%d#256' % j, 'y'], G0), Q) for j in range(P))
    out = header(ns, bs, extra)
    out += 'theorem main %s (y : U256) :\n    %s := by\n  refine ⟨%s⟩\n' % (BIND, conj, ', '.join(['?_'] * P))
    ops = ops_of(prog)
    for j in range(P):
        nd = 5 * min(j + 1, P - 1)  # dispatcher opcodes path j runs
        Aops = block_ops(prog, 'A%d' % j)
        if variant == 'perblock':
            ls = steps(nd, '    ') + ['    exact blockA%d message st ss _ _ _ (by omega)' % j]
        elif variant == 'shared':
            ls = steps(nd + len(Aops), '    ') + ['    exact blockB message st ss _ _ _ (by omega)']
        else:
            ls = steps(nd + len(Aops) + len(Bops) - 1, '    ') + ['  ' + l for l in STOP.split('\n')]
        ls[0] = '  · ' + ls[0].lstrip()
        out += '\n'.join(ls) + '\n'
    write(outdir, 'EvmJoin%d_%s' % (N, variant), out + footer(ns))

def frames(ops):
    stk, pc, gas, frs = ['x', 'y'], 0, G0, []
    for op in ops:
        frs.append((pc, list(stk), gas))
        if op[0] == 'STOP': break
        if op[0] == 'PUSH1': stk = ['%d#256' % op[1]] + stk; pc += 2
        elif op[0] == 'ADD': stk = ['add (%s) (%s)' % (stk[0], stk[1])] + stk[2:]; pc += 1
        elif op[0] == 'SWAP1': stk = [stk[1], stk[0]] + stk[2:]; pc += 1
        elif op[0] == 'JUMPDEST': pc += 1
        else: raise ValueError(op)
        gas -= COST[op[0]]
    return frs

def gen_chain(N, variant, outdir):
    ops = chain_prog(N); bs, _ = assemble(ops)
    ns = 'Verify.Eval.E.Evm.Chain%d_%s' % (N, variant)
    frs = frames(ops); k = N // BLK
    stmt = 'theorem main %s (x y : U256) :\n    Spec fork %s %s := by\n' % (BIND, at(0, ['x', 'y'], G0), Q)
    if variant == 'mono':
        src = header(ns, bs) + stmt + '\n'.join(steps(N)) + '\n' + STOP + '\n'
    else:
        lit = variant.endswith('Lit'); extra = ''
        def fr(i): pc, s, gas = frs[i * BLK]; return at(pc, s, gas)
        def F(i): return fr(i) if lit else '(F%d message st ss x y)' % i
        if not lit:
            for i in range(k + 1):
                extra += ('def F%d %s (x y : U256) : Evm fork Nat → Prop :=\n  %s\n' % (i, BIND, fr(i)))
            extra += '\n'
        for i in range(k):
            pre = '' if lit else '  unfold F%d F%d\n' % (i, i + 1)
            extra += ('theorem blk%d %s (x y : U256) :\n    Hoare fork %s %s := by\n%s'
                      % (i, BIND, F(i), F(i + 1), pre))
            extra += '\n'.join(steps(BLK)) + '\n  exact Triple.of_imp fun _ h => h\n\n'
        lastpc, lasts, lastg = frs[k * BLK]
        extra += ('theorem fin %s (x y : U256) :\n    Spec fork %s %s := by\n%s%s\n\n'
                  % (BIND, F(k), Q, '' if lit else '  unfold F%d\n' % k, STOP))
        bl = ['(blk%d message st ss x y)' % i for i in range(k)]
        last = '(fin message st ss x y)'
        if variant.startswith('lin'):
            term = last
            for b in reversed(bl): term = 'Spec.seq %s (%s)' % (b, term)
        else:
            term = 'Spec.seq (%s) %s' % (tree(bl), last)
        src = header(ns, bs, extra) + stmt + '  exact ' + term + '\n'
    write(outdir, 'EvmChain%d_%s' % (N, variant), src + footer(ns))

if __name__ == '__main__':
    outdir = sys.argv[1]; os.makedirs(outdir, exist_ok=True)
    sizes = [int(a) for a in sys.argv[2:]] or [16, 32, 64, 128, 256]
    for N in sizes:
        for v in ['inline', 'shared', 'perblock']: gen_join(N, v, outdir)
        for v in ['mono', 'linLit', 'balLit', 'linDef', 'balDef']: gen_chain(N, v, outdir)
