#!/bin/sh
# Generates Reconstruct.lean: invariants pasted mechanically from z3 Spacer models; CHC clauses as stated in chc/*.smt2.
set -eu
cd "$(dirname "$0")"
W=115792089237316195423570985008687907853269984665640564039457584007913129639936
out=Reconstruct.lean
{
echo '/-! Kernel-checked initiation / preservation / use for the three loops.'
echo '    Each Inv_* below is generated by smt2lean_inv.py from the z3 Spacer model, unedited.'
echo '    Only Lean core is imported (no Flex, no Mathlib). -/'
echo 'namespace FlexEval'
echo
for v in counter_int counter_u256 okwhile_int okwhile_u256 drain_int drain_u256; do
  python3 smt2lean_inv.py chc/$v.spacer.out Inv_$v; echo
done
cat <<EOF
/-! ## (a) Counter.bump  — vars (c0 = old count, n, lim, i, c = count) -/

-- mathematical Int (uint inputs nonnegative, no overflow guards)
theorem counter_int_init : ∀ c0 n lim : Int,
    0 ≤ c0 → 0 ≤ n → 0 ≤ lim → c0 ≤ lim → c0 + n ≤ lim → Inv_counter_int c0 n lim 0 c0 := by
  intros; simp only [Inv_counter_int]; omega
theorem counter_int_pres : ∀ c0 n lim i c : Int,
    Inv_counter_int c0 n lim i c → i < n → Inv_counter_int c0 n lim (i + 1) (c + 1) := by
  intros; simp only [Inv_counter_int] at *; omega
theorem counter_int_use : ∀ c0 n lim i c : Int,
    Inv_counter_int c0 n lim i c → ¬ (i < n) → c = c0 + n ∧ c ≤ lim := by
  intros; simp only [Inv_counter_int] at *; omega

-- uint256 with Solidity 0.8 checked arithmetic: every op result must lie in [0, 2^256)
theorem counter_u256_init : ∀ c0 n lim : Int,
    0 ≤ c0 → c0 < $W → 0 ≤ n → n < $W → 0 ≤ lim → lim < $W → c0 ≤ lim →
    0 ≤ c0 + n → c0 + n < $W → c0 + n ≤ lim → Inv_counter_u256 c0 n lim 0 c0 := by
  intros; simp only [Inv_counter_u256]; omega
theorem counter_u256_pres : ∀ c0 n lim i c : Int,
    Inv_counter_u256 c0 n lim i c → i < n →
    0 ≤ c + 1 → c + 1 < $W → 0 ≤ i + 1 → i + 1 < $W →
    Inv_counter_u256 c0 n lim (i + 1) (c + 1) := by
  intros; simp only [Inv_counter_u256] at *; omega
theorem counter_u256_use : ∀ c0 n lim i c : Int,
    Inv_counter_u256 c0 n lim i c → ¬ (i < n) → c = c0 + n ∧ c ≤ lim := by
  intros; simp only [Inv_counter_u256] at *; omega

/-! ## (b) ok_while — vars (n, i) -/
theorem okwhile_int_init : ∀ n : Int, 0 ≤ n → Inv_okwhile_int n 0 := by
  intros; simp only [Inv_okwhile_int]; omega
theorem okwhile_int_pres : ∀ n i : Int, Inv_okwhile_int n i → i < n → Inv_okwhile_int n (i + 1) := by
  intros; simp only [Inv_okwhile_int] at *; omega
theorem okwhile_int_use : ∀ n i : Int, Inv_okwhile_int n i → ¬ (i < n) → i = n := by
  intros; simp only [Inv_okwhile_int] at *; omega

theorem okwhile_u256_init : ∀ n : Int, 0 ≤ n → n < $W → Inv_okwhile_u256 n 0 := by
  intros; simp only [Inv_okwhile_u256]; omega
theorem okwhile_u256_pres : ∀ n i : Int, Inv_okwhile_u256 n i → i < n →
    0 ≤ i + 1 → i + 1 < $W → Inv_okwhile_u256 n (i + 1) := by
  intros; simp only [Inv_okwhile_u256] at *; omega
theorem okwhile_u256_use : ∀ n i : Int, Inv_okwhile_u256 n i → ¬ (i < n) → i = n := by
  intros; simp only [Inv_okwhile_u256] at *; omega

/-! ## (c) drain — vars (n, a, b) -/
theorem drain_int_init : ∀ n : Int, 0 ≤ n → Inv_drain_int n n 0 := by
  intros; simp only [Inv_drain_int]; omega
theorem drain_int_pres : ∀ n a b : Int, Inv_drain_int n a b → a > 0 → Inv_drain_int n (a - 1) (b + 1) := by
  intros; simp only [Inv_drain_int] at *; omega
theorem drain_int_use : ∀ n a b : Int, Inv_drain_int n a b → ¬ (a > 0) → b = n := by
  intros; simp only [Inv_drain_int] at *; omega

theorem drain_u256_init : ∀ n : Int, 0 ≤ n → n < $W → Inv_drain_u256 n n 0 := by
  intros; simp only [Inv_drain_u256]; omega
theorem drain_u256_pres : ∀ n a b : Int, Inv_drain_u256 n a b → a > 0 →
    0 ≤ a - 1 → a - 1 < $W → 0 ≤ b + 1 → b + 1 < $W → Inv_drain_u256 n (a - 1) (b + 1) := by
  intros; simp only [Inv_drain_u256] at *; omega
theorem drain_u256_use : ∀ n a b : Int, Inv_drain_u256 n a b → ¬ (a > 0) → b = n := by
  intros; simp only [Inv_drain_u256] at *; omega

end FlexEval
EOF
for v in counter_int counter_u256 okwhile_int okwhile_u256 drain_int drain_u256; do
  for k in init pres use; do echo "#print axioms FlexEval.${v}_$k"; done
done
} > $out
echo generated $out
