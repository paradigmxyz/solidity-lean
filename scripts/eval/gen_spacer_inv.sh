#!/bin/sh
# Regenerates Verify/Eval/D/SpacerInv.lean: z3 Spacer's invariant for Counter.bump
# (Verify/Infer/chc/counter_u256.spacer.out), translated 1:1 by Verify/Infer/smt2lean_inv.py.
set -eu
cd "$(dirname "$0")/../.."
out=Verify/Eval/D/SpacerInv.lean
{
  echo '/-! Generated by scripts/eval/gen_spacer_inv.sh from Verify/Infer/chc/counter_u256.spacer.out'
  echo '    with Verify/Infer/smt2lean_inv.py (unedited). Lean core only. -/'
  echo 'namespace SolidCore.Verify.Eval.D.Spacer'
  echo
  python3 Verify/Infer/smt2lean_inv.py Verify/Infer/chc/counter_u256.spacer.out Inv_counter_u256
  echo
  echo 'end SolidCore.Verify.Eval.D.Spacer'
} > "$out"
