#!/usr/bin/env python3
"""Generate Lane A's SolM scaling fixtures: Verify/Eval/A/Fixtures/<Family><n>.lean.

    scripts/eval/fixtures/gen_solm.py [--sizes 16,32,64,128,256] [--families Straight,...]

Each fixture states one Loom weakest-precondition goal on the repository's `SolM` monad
(Verify/Basic.lean) as `def Verify.Eval.A.<Family><n>.stmt : Prop`, and proves it with today's
engine as `theorem Verify.Eval.A.<Family><n>.baseline : stmt`: the `simp only [wp_bind, wp_pure,
wp_sload, wp_sstore, wp_revert, wp_ite]` cascade of `sc_vcgen`, then `sc_close`
(Verify/Tactic.lean). Other lanes prove the same `stmt` with their engine beside it.

`n` counts the model's monadic primitives (`sload`, `sstore`, and a guard `if c then pure ()
else revert d`, one op each). Families (docs/eval/a.md):

* Straight : n/2 load/store pairs in one chain, slot i+1 := slot i + 1.
* Shared   : one expression of slot 0 stored into n-1 slots; the postcondition repeats it.
* Branch   : n/3 sequential require-style guards, each a load, a guarded revert and a store
             (n/3 + 1 paths, not 2^n).
* Memory   : n/2 - 1 distinct slots written, then read back and returned.
* LoopBody : a loop body of n/2 increments (load, store) proved against a supplied invariant and
             variant in `triple` form, as `triple_whileM` asks of it.
"""
import argparse
import pathlib

REPO = pathlib.Path(__file__).resolve().parents[3]
OUT = REPO / "Verify" / "Eval" / "A" / "Fixtures"
W = "2 ^ 256"

HEADER = """import Verify.Basic
import Verify.Tactic
import Verify.Eval.Common.Measure

/-!
# Lane A fixture: {fam} family, n = {n} ops

Generated by scripts/eval/fixtures/gen_solm.py; do not edit by hand.

{doc}

`stmt` is the statement every lane proves; `baseline` is today's engine (the `sc_vcgen`
cascade: `simp only [wp_bind, wp_pure, wp_sload, wp_sstore, wp_revert, wp_ite]`, then
`sc_close`).
-/

set_option maxHeartbeats 0
set_option maxRecDepth 100000
set_option linter.unusedSimpArgs false

namespace Verify.Eval.A.{name}

open SolidCore.Verify

"""

FOOTER = """
end Verify.Eval.A.{name}

#proof_stats Verify.Eval.A.{name}.baseline
#kernel_recheck Verify.Eval.A.{name}.baseline
"""

WP = "wp_bind, wp_pure, wp_sload, wp_sstore, wp_revert, wp_ite, ite_apply, dite_apply"


def conj(xs):
    return " ∧\n      ".join(xs) if xs else "True"


def straight(n):
    m = n // 2
    body = []
    for i in range(m):
        body.append(f"  let v{i} ← sload {i}")
        body.append(f"  sstore {i + 1} (v{i} + 1)")
    model = "def model : SolM Unit := do\n" + "\n".join(body) + "\n"
    stmt = (f"def stmt : Prop :=\n  ∀ (s : Storage) (herr : Revert → Prop), s 0 < 2 ^ 128 →\n"
            f"    wp model (fun _ _ s' => s' {m} = s 0 + {m}) herr s\n")
    proof = (f"theorem baseline : stmt := by\n  intro s herr h\n"
             f"  simp only [model, {WP}]\n  sc_close\n")
    doc = (f"{m} load/store pairs: `slot i+1 := slot i + 1` for i < {m}; from `s 0 < 2^128`, "
           f"slot {m} ends as `s 0 + {m}` (each store wraps modulo 2^256, so `omega` sees {m} nested `%`).")
    return doc, model + "\n" + stmt + "\n" + proof


def shared(n):
    m = n - 1
    body = ["  let x ← sload 0"] + [f"  sstore {i} ((x + 1) * (x + 2) + x * 3)" for i in range(1, m + 1)]
    model = "def model : SolM Unit := do\n" + "\n".join(body) + "\n"
    e = f"((s 0 + 1) * (s 0 + 2) + s 0 * 3) % {W}"
    stmt = ("def stmt : Prop :=\n  ∀ (s : Storage) (herr : Revert → Prop),\n"
            "    wp model (fun _ _ s' =>\n      " + conj([f"s' {i} = {e}" for i in range(1, m + 1)]) +
            ") herr s\n")
    proof = (f"theorem baseline : stmt := by\n  intro s herr\n"
             f"  simp only [model, {WP}]\n  sc_close\n")
    doc = (f"One expression `(x + 1) * (x + 2) + x * 3` of `x = s 0` stored into slots 1..{m}; "
           f"the postcondition repeats it {m} times (one shared subterm, used many times).")
    return doc, model + "\n" + stmt + "\n" + proof


def branch(n):
    g = n // 3
    body = []
    for i in range(g):
        body.append(f"  let v{i} ← sload {i}")
        body.append(f"  if v{i} < 2 ^ 255 then pure () else revert [{i}]")
        body.append(f"  sstore {1000 + i} (v{i} + v{i})")
    model = "def model : SolM Unit := do\n" + "\n".join(body) + "\n"
    stmt = ("def stmt : Prop :=\n  ∀ (s : Storage) (herr : Revert → Prop), (∀ e, herr e) →\n"
            "    wp model (fun _ _ s' =>\n      " +
            conj([f"s' {1000 + i} = 2 * s {i}" for i in range(g)]) + ") herr s\n")
    proof = (f"theorem baseline : stmt := by\n  intro s herr hrev\n"
             f"  simp only [model, {WP}]\n  sc_close\n")
    doc = (f"{g} sequential `require(slot i < 2^255)` guards, each followed by a store of the doubled "
           f"value (a load, a guarded revert and a store: 3 ops). Paths: {g + 1}. Any revert is allowed "
           f"(`∀ e, herr e`); on success each doubled slot holds `2 * s i` exactly (no wrap, by the guard).")
    return doc, model + "\n" + stmt + "\n" + proof


def memory(n):
    m = n // 2
    body = ["  let x ← sload 0"]
    for i in range(m - 1):
        body.append(f"  sstore {100 + i} (x + {i})")
    for i in range(m - 1):
        body.append(f"  let r{i} ← sload {100 + i}")
    out = ", ".join(f"r{i}" for i in range(m - 1))
    body.append(f"  pure [{out}]")
    model = "def model : SolM (List Nat) := do\n" + "\n".join(body) + "\n"
    exp = ", ".join(f"(s 0 + {i}) % {W}" for i in range(m - 1))
    stmt = ("def stmt : Prop :=\n  ∀ (s : Storage) (herr : Revert → Prop),\n"
            f"    wp model (fun out _ _ => out = [{exp}]) herr s\n")
    proof = (f"theorem baseline : stmt := by\n  intro s herr\n"
             f"  simp only [model, {WP}]\n  sc_close\n")
    doc = (f"Load slot 0, write {m - 1} distinct slots 100.. with `x + i`, read all {m - 1} back "
           f"through the {m - 1} writes and return them ({2 * m - 1} ops).")
    return doc, model + "\n" + stmt + "\n" + proof


def loopbody(n):
    m = n // 2
    body = []
    for j in range(m):
        body.append(f"  let c{j} ← sload {j}")
        body.append(f"  sstore {j} (c{j} + 1)")
    body.append("  pure (i + 1)")
    model = "def body (i : Nat) : SolM Nat := do\n" + "\n".join(body) + "\n"
    inv_parts = ["i ≤ N"] + [f"s' {j} = s {j} + i" for j in range(m)] + [f"s {j} + N < 2 ^ 256" for j in range(m)]
    inv = ("/-- The supplied invariant: `i ≤ N`, every counter advanced by `i`, and the bound the\n"
           "caller established. -/\n"
           "def inv (N : Nat) (s : Storage) (i : Nat) : Assn := fun _ s' =>\n      " + conj(inv_parts) + "\n")
    var = "/-- The supplied variant. -/\ndef variant (N i : Nat) : Nat := N - i\n"
    stmt = ("def stmt : Prop :=\n  ∀ (N : Nat) (s : Storage) (i : Nat), decide (i < N) = true →\n"
            "    triple (inv N s i) (body i) (fun i' => inv N s i' ⊓ ⌜variant N i' < variant N i⌝)\n")
    proof = (f"theorem baseline : stmt := by\n  intro N s i hi herr s' hinv\n"
             f"  simp only [decide_eq_true_eq] at hi\n"
             f"  simp only [inv] at hinv\n"
             f"  obtain ⟨{', '.join(['hle'] + [f'h{j}' for j in range(m)] + [f'b{j}' for j in range(m)])}⟩ := hinv\n"
             f"  have hv : N - (i + 1) < N - i := by omega\n"
             f"  simp only [body, inv, variant, {WP}, LE.pure, hv, ↓reduceIte,\n"
             f"    Pi.inf_apply, inf_Prop_eq, Pi.top_apply, Pi.bot_apply, Prop.top_eq_true, Prop.bot_eq_false]\n  sc_close\n")
    doc = (f"The body of `while i < N` with {m} counters (slots 0..{m - 1}), each incremented by a "
           f"load and a store ({n} ops), proved against the supplied invariant and variant in the "
           f"`triple` form `triple_whileM` asks of a body (as `CounterBump.body_step`).")
    return doc, model + "\n" + inv + "\n" + var + "\n" + stmt + "\n" + proof


FAMILIES = {"Straight": straight, "Shared": shared, "Branch": branch, "Memory": memory, "LoopBody": loopbody}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sizes", default="16,32,64,128,256")
    ap.add_argument("--families", default=",".join(FAMILIES))
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    for fam in a.families.split(","):
        for n in map(int, a.sizes.split(",")):
            name = f"{fam}{n}"
            doc, body = FAMILIES[fam](n)
            src = HEADER.format(fam=fam, n=n, doc=doc, name=name) + body + FOOTER.format(name=name)
            (OUT / f"{name}.lean").write_text(src)
            print(OUT / f"{name}.lean")


if __name__ == "__main__":
    main()
