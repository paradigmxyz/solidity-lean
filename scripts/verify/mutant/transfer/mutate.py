#!/usr/bin/env python3
"""Mutation acceptance for UniswapV2ERC20.transfer's certified statement.

mutate.py [--solar-dir DIR] [--only NAME,...] [--work DIR] [--table OUT.md]

Run from the repository root after lake build ContractsUniswapV2ERC20Certified (run.sh does
both). Each mutation edits one file in the import closure of
Contracts.UniswapV2.ERC20.Certified.Transfer, in a scratch copy (the tree is never written), then
recompiles, into an overlay of object files searched before .lake/build, every module of the
closure that imports the edited one, in import order, with the options the lakefile gives its
library and -M 6000. The mutation is rejected when one of them fails to check; the table names
the first failing module, its declaration and the first error. The control compiles the same
modules from the unedited sources the same way and must pass, so a rejection comes from the
edit, not from the overlay.

Bytes mutations change the runtime bytes (gen/UniswapV2ERC20/Bytecode.lean and its manifest) and
are checked twice: (a) against the certificate generated for the real bytes (only the bytes
change), and (b) with the certificate regenerated by solar's gen_ctxgas.py for the mutated bytes
(the untrusted inference rerun on them). Such a mutation counts as rejected only when both are.
"""
import argparse, json, os, pathlib, re, shutil, subprocess, sys, time

ROOT_MOD = "Contracts.UniswapV2.ERC20.Certified.Transfer"
SRC_DIRS = [".", "Certified", "tv", "vendor/evm-rules"]
# Libraries under these directories take solarTVOptions (lakefile.lean); the rest the package's.
TV_DIRS = {"Certified", "tv", "vendor/evm-rules"}
PKG_OPTS = ["-DmaxHeartbeats=1000000", "-Dbackward.do.legacy=true"]
TV_OPTS = ["-DmaxHeartbeats=200000", "-Dbackward.do.legacy=false"]
MEM = ["-M", "6000"]
BUILD = pathlib.Path(".lake/build/lib/lean").resolve()

GEN = "Certified/uv2_erc20/gen/UniswapV2ERC20"
BYTECODE = f"{GEN}/Bytecode.lean"
POST = "Contracts/UniswapV2/ERC20/Slice/Post.lean"
TRANSFER = "Contracts/UniswapV2/ERC20/Certified/Transfer.lean"
GAS = "Certified/uv2_erc20/Gas.lean"
GUARD = "Certified/uv2_erc20/GasGuard.lean"
CTXGAS = "Certified/uv2_erc20/CtxGas.lean"

# The check a failing module stands for.
CHECKS = {
    "uv2_erc20.gen.UniswapV2ERC20.Bytecode": "bytes module (elaboration)",
    "uv2_erc20.CtxGas": "E5 bytes checker (AssembleCtxGas, kernel evaluation)",
    "uv2_erc20.GasGuard": "E8 guard stage (sym_exec)",
    "uv2_erc20.Gas": "gas bound (kernel evaluation of gasBoundL)",
    "Contracts.UniswapV2.ERC20.Slice.Post": "E7 postcondition (elaboration)",
    "Contracts.UniswapV2.ERC20.Slice.Run": "E7 spec proof over SolidCore runs",
    "Contracts.UniswapV2.ERC20.Slice.Vc": "E7 VC discharge",
    "Contracts.UniswapV2.ERC20.Slice.Statement": "E7 meets_target",
    "Contracts.UniswapV2.ERC20.Slice.Bytes": "E7 transfer through Equiv",
    ROOT_MOD: "final statement (Transfer)",
}


# ---------------------------------------------------------------- the import graph

def mod_file(mod):
    rel = mod.replace(".", "/") + ".lean"
    for d in SRC_DIRS:
        p = pathlib.Path(d) / rel
        if p.is_file():
            return d, p
    return None, None


IMPORT_LINE = re.compile(r"^(?:public\s+|private\s+)?(?:meta\s+)?import\s+(?:all\s+)?(\S+)")


def imports_of(path):
    out, in_block = [], False
    for line in path.read_text().splitlines():
        s = line.strip()
        if in_block:
            if "-/" in s:
                in_block = False
            continue
        if s.startswith("/-") and not s.startswith("/-!") and not s.startswith("/--"):
            in_block = "-/" not in s
            continue
        if s == "" or s.startswith("--") or s == "module" or s.startswith("prelude"):
            continue
        m = IMPORT_LINE.match(s)
        if not m:
            break
        out.append(m.group(1))
    return out


def closure(root):
    deps, order, seen = {}, [], set()

    def go(m):
        if m in seen:
            return
        seen.add(m)
        _, p = mod_file(m)
        deps[m] = imports_of(p) if p is not None else []  # a package's module: lake built it
        for x in deps[m]:
            go(x)
        order.append(m)

    go(root)
    return deps, order  # every module after its imports


def dependents(deps, order, edited):
    hit = set(edited)
    for m in order:
        if any(x in hit for x in deps[m]):
            hit.add(m)
    return [m for m in order if m in hit]


# ---------------------------------------------------------------- compiling into the overlay

def lake_env(var):
    return subprocess.run(["lake", "env", "printenv", var], capture_output=True, text=True, check=True).stdout.strip()


class Compiler:
    def __init__(self, work):
        self.work = pathlib.Path(work).resolve()
        self.lean = pathlib.Path(lake_env("LEAN_SYSROOT")) / "bin" / "lean"
        self.lean_path = lake_env("LEAN_PATH")
        self.receipts = []

    def compile_chain(self, name, mods, sources):
        """Compile mods in order into overlay name; sources maps a module to its replacement text.
        None when every module checks, else the first failure."""
        base = self.work / name
        if base.exists():
            shutil.rmtree(base)
        ov = base / "olean"
        ov.mkdir(parents=True)
        # Lean takes each import's first path component from the first search directory that has
        # it, so the overlay mirrors .lake/build's tree of every root it recompiles (symbolic
        # links), and each recompiled module replaces its link.
        for r in sorted({m.split(".")[0] for m in mods}):
            subprocess.run(["cp", "-rs", str(BUILD / r), str(ov / r)], check=True)
        env = dict(os.environ)
        env.pop("LD_LIBRARY_PATH", None)
        env["LEAN_PATH"] = f"{ov}:{self.lean_path}"
        env["LEAN_NUM_THREADS"] = "1"
        for m in mods:
            d, p = mod_file(m)
            if m in sources:
                # The edited copy sits under a scratch root at the same relative path, so the
                # module name -R derives is unchanged.
                root = base / "src" / d
                file = root / p.relative_to(d)
                file.parent.mkdir(parents=True, exist_ok=True)
                file.write_text(sources[m])
            else:
                root, file = pathlib.Path(d).resolve(), p.resolve()
            out = ov / (m.replace(".", "/") + ".olean")
            out.parent.mkdir(parents=True, exist_ok=True)
            for f in out.parent.glob(out.stem + ".*"):
                if f.is_symlink():
                    f.unlink()  # never write through a link into .lake/build
            opts = TV_OPTS if d in TV_DIRS else PKG_OPTS
            cmd = [str(self.lean), "-R", str(root), "-o", str(out), "-i", str(out.with_suffix(".ilean"))] \
                + opts + MEM + [str(file)]
            log = base / "log" / (m + ".txt")
            log.parent.mkdir(parents=True, exist_ok=True)
            t = time.time()
            with open(log, "w") as f:
                f.write(" ".join(cmd) + "\n")
                f.flush()
                pr = subprocess.Popen(cmd, env=env, stdout=f, stderr=subprocess.STDOUT)
                _, status, ru = os.wait4(pr.pid, 0)
                pr.returncode = os.waitstatus_to_exitcode(status)
            wall = round(time.time() - t)
            self.receipts.append(dict(run=name, module=m, exit=pr.returncode, wall_s=wall,
                                      peak_rss_mb=ru.ru_maxrss // 1024))
            print(f"  [{name}] {m}: exit {pr.returncode} ({wall} s, {ru.ru_maxrss // 1024} MB)", flush=True)
            if pr.returncode != 0:
                return failure(m, file, log.read_text().split("\n", 1)[1])
        return None


DECL = re.compile(r"^\s*(?:@\[[^\]]*\]\s*)?(?:private\s+|protected\s+|noncomputable\s+)*"
                  r"(theorem|lemma|def|abbrev|instance|example|structure|inductive)\s+([^\s:({\[]*)")


def failure(mod, file, out):
    m = re.search(r":(\d+):\d+: error:?\s*(.*)", out)
    if not m:
        line, msg = 0, (out.strip().splitlines() or ["(no output)"])[-1]
    else:
        line, msg = int(m.group(1)), m.group(2).strip()
        if not msg:
            rest = out[m.end():].strip().splitlines()
            msg = rest[0] if rest else ""
    decl = ""
    lines = pathlib.Path(file).read_text().splitlines()
    for i in range(min(line, len(lines)) - 1, -1, -1):
        dm = DECL.match(lines[i])
        if dm:
            decl = dm.group(2) or dm.group(1)
            break
    return dict(module=mod, decl=decl, line=line, error=msg[:160])


# ---------------------------------------------------------------- the mutations

def replace_once(text, old, new, after=None):
    start = text.index(after) if after else 0
    i = text.find(old, start)
    if i < 0:
        raise SystemExit(f"error: mutation anchor not found: {old!r}")
    if after is None and text.count(old) != 1:
        raise SystemExit(f"error: mutation anchor not unique: {old!r}")
    return text[:i] + new + text[i + len(old):]


def read_bytes():
    return bytearray(bytes.fromhex(json.loads(pathlib.Path(GEN, "manifest.json").read_text())["bytecode"]))


def decode(code):
    """Instruction offsets of the runtime bytes."""
    i, out = 0, []
    while i < len(code):
        out.append(i)
        op = code[i]
        i += 1 + (op - 0x5f if 0x60 <= op <= 0x7f else 0)
    return out


def bytecode_lean(code):
    text = pathlib.Path(BYTECODE).read_text()
    start = text.index("def bytecode : List Nat :=")
    lb = text.index("[", start)
    rb = text.index("]", lb)
    rows = [", ".join(f"0x{b:02x}" for b in code[i:i + 16]) for i in range(0, len(code), 16)]
    return text[:lb] + "[" + ",\n   ".join(rows) + "]" + text[rb + 1:]


def wrong_branch(code):
    # The dispatcher's PUSH4 0xa9059cbb EQ PUSH2 dest JUMPI: jump to another function's entry.
    pat = re.compile(rb"\x63(....)\x14\x61(..)\x57", re.S)
    hits = [(m.start(), m.group(1), int.from_bytes(m.group(2), "big")) for m in pat.finditer(bytes(code))]
    tr = [h for h in hits if h[1] == bytes.fromhex("a9059cbb")]
    assert len(tr) == 1, tr
    at, _, dest = tr[0]
    other = next(h for h in hits if h[2] != dest and code[h[2]] == 0x5b)
    code[at + 7:at + 9] = other[2].to_bytes(2, "big")
    return (f"dispatcher at 0x{at:x}: transfer's JUMPI target 0x{dest:x} -> 0x{other[2]:x} "
            f"(selector 0x{other[1].hex()}'s entry)")


def revert_to_return(code):
    # The SafeMath error path: PUSH21 "ds-math-sub-underflow" ... PUSH2 helper JUMP; the helper's
    # REVERT becomes RETURN, so a failing transfer succeeds with the error data.
    msg = b"ds-math-sub-underflow"
    at = bytes(code).index(bytes([0x5f + len(msg)]) + msg)
    offs = decode(code)
    k = offs.index(at)
    j = next(o for o in offs[k:] if code[o] == 0x56)
    helper = int.from_bytes(code[j - 2:j], "big")
    assert code[j - 3] == 0x61 and code[helper] == 0x5b, (hex(j), hex(helper))
    r = next(o for o in offs[offs.index(helper):] if code[o] == 0xfd)
    code[r] = 0xf3
    return f"error helper 0x{helper:x} (jumped to from sub-underflow at 0x{at:x}): REVERT at 0x{r:x} -> RETURN"


def flip_byte(code):
    i = len(code) // 2
    old = code[i]
    code[i] ^= 0x01
    return f"byte 0x{i:x} of {len(code)}: 0x{old:02x} -> 0x{code[i]:02x}"


def bytes_mutation(fn):
    def go():
        code = read_bytes()
        return fn(code), code
    return go


def text_mutation(path, old, new, after=None, what=""):
    def go():
        return what, {path: replace_once(pathlib.Path(path).read_text(), old, new, after)}
    return go


def step_budget():
    t = pathlib.Path(GUARD).read_text()
    t2 = replace_once(t, "def N : Nat := 7", "def N : Nat := 6").replace("call 7", "call 6")
    return "GasGuard: block budget N 7 -> 6 (the guard's runs at 6 blocks)", {GUARD: t2}


MUTATIONS = [
    ("wrong-branch-target", "bytes", bytes_mutation(wrong_branch)),
    ("self-transfer-alias", "text", text_mutation(
        POST, "    (caller ≠ dst →\n      (obs.success = true ↔", "    (True →\n      (obs.success = true ↔",
        what="TargetPost: the distinct-accounts clause (debit, credit, recipient overflow) also for caller = to")),
    ("revert-path", "bytes", bytes_mutation(revert_to_return)),
    ("balance-boundary", "text", text_mutation(
        POST, "        v ≤ slotValue σ (balKey caller) ∧ slotValue σ (balKey dst) + v < 2 ^ 256) ∧",
        "        v ≤ slotValue σ (balKey caller) ∧ slotValue σ (balKey dst) + v ≤ 2 ^ 256) ∧",
        what="TargetPost: recipient bound s[to] + v < 2^256 -> <= 2^256 (success claimed at s[to] + v = 2^256)")),
    ("gas-exhaustion", "text", text_mutation(
        GAS, "theorem G_eq : G = 8199112", "theorem G_eq : G = 8199111",
        what="Gas: claimed bound one below the computed one, 8199112 -> 8199111")),
    ("step-budget-exhaustion", "text", step_budget),
    ("flipped-byte", "bytes", bytes_mutation(flip_byte)),
    ("wrong-expected-type", "text", text_mutation(
        TRANSFER, "Certified (solidCore fuel) c code ValidIn Allowed TargetPost (fun _ => 8199112) := by",
        "Certified (solidCore fuel) c code ValidIn Allowed\n      (fun call obs => TargetPost call obs ∧ obs.success = true) (fun _ => 8199112) := by",
        after="theorem certified :",
        what="certified: postcondition TargetPost -> TargetPost ∧ success (every call claimed to succeed)")),
]


def mod_of_path(path):
    p = pathlib.Path(path)
    for d in SRC_DIRS:
        if d != "." and str(p).startswith(d + "/"):
            return str(p.relative_to(d).with_suffix("")).replace("/", ".")
    return str(p.with_suffix("")).replace("/", ".")


def regen(solar_dir, gen, out, check=True):
    cmd = [sys.executable, str(pathlib.Path(solar_dir, "tools/certify/gen_ctxgas.py")), str(gen),
           "--module-prefix", "uv2_erc20.gen.UniswapV2ERC20", "--contract", "UniswapV2ERC20",
           "--final", "evm11", "--selector", "0xa9059cbb", "--out", str(out)]
    return subprocess.run(cmd, capture_output=True, text=True, check=check)


def fmt(r):
    if r is None:
        return "ACCEPTED"
    check = CHECKS.get(r["module"], r["module"])
    d = f" `{r['decl']}`" if r["decl"] else ""
    err = r["error"].replace("|", "\\|").replace("`", "'")
    return f"{check}:{d} ({r['module']}:{r['line']}) {err}"


# ---------------------------------------------------------------- driver

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--solar-dir", default=os.environ.get("SOLAR_DIR"))
    ap.add_argument("--only", default=None)
    ap.add_argument("--work", default=".lake/mutant-transfer")
    ap.add_argument("--table", default=None)
    ap.add_argument("--no-control", action="store_true")
    a = ap.parse_args()
    deps, order = closure(ROOT_MOD)
    comp = Compiler(a.work)
    sel = [m for m in MUTATIONS if not a.only or m[0] in a.only.split(",")]
    any_bytes = any(k == "bytes" for _, k, _ in sel)

    jobs = []
    for name, kind, fn in sel:
        what, res = fn()
        if kind == "bytes":
            jobs.append((name, kind, what, {mod_of_path(BYTECODE): bytecode_lean(res)}, res))
        else:
            jobs.append((name, kind, what, {mod_of_path(p): s for p, s in res.items()}, None))
    edited = sorted({m for j in jobs for m in j[3]} | ({mod_of_path(CTXGAS)} if any_bytes else set()))
    for m in edited:
        assert m in deps, f"{m} is not in {ROOT_MOD}'s closure"

    ctl_mods = dependents(deps, order, edited)
    ctl = "skipped"
    if not a.no_control:
        print(f"control: {len(ctl_mods)} modules from the unedited sources", flush=True)
        ctl = comp.compile_chain("control", ctl_mods, {})
    regen_ok = None
    if any_bytes and a.solar_dir:
        out = pathlib.Path(a.work, "regen-control.lean")
        out.parent.mkdir(parents=True, exist_ok=True)
        regen(a.solar_dir, pathlib.Path(GEN), out)
        regen_ok = out.read_text() == pathlib.Path(CTXGAS).read_text()
        print(f"control: certificate regenerated from the real bytes equals {CTXGAS}: {regen_ok}", flush=True)

    rows = []
    for name, kind, what, srcs, code in jobs:
        print(f"mutation {name}: {what}", flush=True)
        res_a = comp.compile_chain(name, dependents(deps, order, list(srcs)), srcs)
        res_b, note_b = None, None
        if kind == "bytes":
            if not a.solar_dir:
                note_b = "not run (no SOLAR_DIR)"
            else:
                g = pathlib.Path(a.work, name + "-gen")
                if g.exists():
                    shutil.rmtree(g)
                shutil.copytree(GEN, g)
                man = json.loads((g / "manifest.json").read_text())
                man["bytecode"] = bytes(code).hex()
                (g / "manifest.json").write_text(json.dumps(man, indent=2))
                (g / "Bytecode.lean").write_text(srcs[mod_of_path(BYTECODE)])
                out = pathlib.Path(a.work, name + "-CtxGas.regen.lean")
                r = regen(a.solar_dir, g, out, check=False)
                if r.returncode != 0:
                    msg = ((r.stderr or r.stdout).strip().splitlines() or [""])[-1][:140]
                    res_b = dict(module="gen_ctxgas.py", decl="", line=0, error=msg)
                    note_b = "certificate inference refuses: " + msg
                else:
                    srcs_b = dict(srcs)
                    srcs_b[mod_of_path(CTXGAS)] = out.read_text()
                    res_b = comp.compile_chain(name + "+regen", dependents(deps, order, list(srcs_b)), srcs_b)
                    note_b = fmt(res_b)
        rejected = res_a is not None and (kind != "bytes" or res_b is not None)
        rows.append(dict(name=name, what=what, rejected=rejected, by=res_a, regen=note_b))

    lines = ["| mutation | edit | rejected | rejected by (first failing check) | bytes: with a certificate regenerated for them |",
             "|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['name']} | {r['what']} | {'yes' if r['rejected'] else '**NO**'} | {fmt(r['by'])} | "
                     f"{r['regen'] if r['regen'] is not None else 'n/a'} |")
    lines.append("")
    lines.append(f"control: the same {len(ctl_mods)} modules from the unedited sources, compiled the same way: "
                 + ("pass" if ctl is None else ("skipped" if ctl == "skipped" else "FAILED " + fmt(ctl))))
    if regen_ok is not None:
        lines.append(f"control: the certificate regenerated from the real bytes equals {CTXGAS}: "
                     + ("pass" if regen_ok else "FAILED"))
    table = "\n".join(lines)
    print("\n" + table + "\n\nreceipts:")
    for x in comp.receipts:
        print(f"  RECEIPT run={x['run']} module={x['module']} exit={x['exit']} wall_s={x['wall_s']} peak_rss_mb={x['peak_rss_mb']}")
    if a.table:
        pathlib.Path(a.table).write_text(table + "\n")
    ok = ctl in (None, "skipped") and regen_ok is not False and all(r["rejected"] for r in rows)
    print("\nMUTATION-ACCEPTANCE " + ("PASS" if ok else "FAIL"))
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
