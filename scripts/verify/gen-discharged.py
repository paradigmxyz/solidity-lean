#!/usr/bin/env python3
"""Write Lean modules that discharge a solar-verify --dump-lean script in the kernel.

Usage: gen-discharged.py MODULE NAMESPACE IMPORT SCRIPT COUNT [--chunk K]
           [--reject IMPORT SCRIPT INDEX]...

Run from the repository root. Writes MODULE (its path from its name) and, for every K obligations,
MODULE.Part<k>: one theorem per obligation (dischargeAt SCRIPT i = true, by decide +kernel), so each
kernel evaluation stays small and each Lean process holds few of them; then MODULE proves the
count of obligations and script_valid : Valid SCRIPT from dischargeScript_of_each. Each --reject
names a mutant script and an obligation index the discharge rejects there, so that
dischargeScript MUTANT = false (dischargeScript_false_of): a mismatch, not a timeout.
"""
import os
import sys

HEADER = "set_option maxRecDepth 100000"


def write(module, lines):
    path = module.replace(".", "/") + ".lean"
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write("\n".join(lines))


def main(argv):
    module, ns, imp, script, count = argv[:5]
    count = int(count)
    chunk = 4
    rejects = []
    rest = argv[5:]
    while rest:
        if rest[0] == "--chunk":
            chunk = int(rest[1])
            rest = rest[2:]
        elif rest[0] == "--reject":
            rejects.append((rest[1], rest[2], int(rest[3])))
            rest = rest[4:]
        else:
            sys.exit(f"unknown argument {rest[0]}")
    parts = []
    for k, lo in enumerate(range(0, count, chunk)):
        part = f"{module}.Part{k}"
        parts.append(part)
        L = ["import Verify.VC.Discharge", f"import {imp}", "",
             f"/-! Obligations {lo} to {min(count, lo + chunk) - 1} of `{script}`, each discharged by the",
             "kernel (generated by scripts/verify/gen-discharged.py). -/", "",
             f"namespace {ns}", "", "open SolidCore.Verify.VC", "", HEADER, ""]
        for i in range(lo, min(count, lo + chunk)):
            L += [f"theorem ob_{i} : dischargeAt {script} {i} = true := by decide +kernel", ""]
        L += [f"end {ns}", ""]
        write(part, L)
    imports = parts + [r[0] for r in rejects]
    seen = []
    for i in imports:
        if i not in seen:
            seen.append(i)
    L = [f"import {i}" for i in seen]
    L += ["", "/-!", f"# `{script}`, discharged by the kernel", "",
          "Generated by scripts/verify/gen-discharged.py: one kernel evaluation of `dischargeAt` per",
          "obligation (the Part modules, Verify/VC/Discharge.lean), and the script's verdict `Valid` from",
          "them, with no solver. Each rejected mutant script fails by a mismatch at the obligation named.",
          "-/", "", f"namespace {ns}", "", "open SolidCore.Verify.VC", "", HEADER, "",
          f"theorem obligation_count : (obligations {script}).length = {count} := by decide +kernel", "",
          "/-- Every obligation of the script has no model. -/",
          f"theorem script_valid : Valid {script} :=",
          "  dischargeScript_of_each _ fun i hi =>",
          "    match i, obligation_count \u25b8 hi with"]
    L += [f"    | {i}, _ => ob_{i}" for i in range(count)]
    L += [f"    | _ + {count}, h => absurd h (by omega)", ""]
    for k, (_, m, idx) in enumerate(rejects):
        L += [f"/-- The mutant script is rejected at obligation {idx}. -/",
              f"theorem reject_{k} : dischargeScript {m} = false :=",
              f"  dischargeScript_false_of (i := {idx}) (by decide +kernel) (by decide +kernel)", ""]
    L += [f"/-- info: '{ns}.script_valid' depends on axioms: [propext, Classical.choice, Quot.sound] -/",
          "#guard_msgs (whitespace := lax) in", "#print axioms script_valid", "", f"end {ns}", ""]
    write(module, L)


if __name__ == "__main__":
    main(sys.argv[1:])
