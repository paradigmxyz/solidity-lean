#!/usr/bin/env python3
"""Writes Contracts/UniswapV2/C/Core.lean: SolidCore's checked Uniswap V2 contract C, with
its selectors by table.

    scripts/verify/uniswap_v2_core.py [--solc SOLC] [--check]

Reads the generated scripts/verify/uniswap-v2/NAME.sol (scripts/verify/uniswap_v2_sources.py) for
the signatures solc hashes, of every contract and interface in the file, since SolidCore's checker
hashes the interfaces' signatures too. Each selector is proved once by Keccak-256 in the kernel
(`kernel_rfl`) and `selector_eq` replaces `ABI.selectorFromSignature` by the table, as
Contracts/Token/VC/Burn.lean does for Token. `contract_ok` is the kernel's type check of the
contract. The module holds no v2-core code, only its ABI signatures.
"""

import argparse
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
CONTRACTS = [("UniswapV2ERC20", "ERC20"), ("UniswapV2Pair", "Pair"), ("UniswapV2Factory", "Factory")]


def signatures(solc: str, sol: pathlib.Path) -> tuple[list[tuple[str, int]], list[tuple[str, int]]]:
    """The function selectors and the event topics solc hashes, of every contract in the file."""
    out = subprocess.run([solc, "--hashes", str(sol)], check=True, capture_output=True,
                         text=True).stdout
    sels: dict[str, int] = {}
    topics: dict[str, int] = {}
    for m in re.finditer(r"^([0-9a-f]{8}|[0-9a-f]{64}): (\S+)$", out, re.M):
        (sels if len(m.group(1)) == 8 else topics).setdefault(m.group(2), int(m.group(1), 16))
    return sorted(sels.items()), sorted(topics.items())


def ident(sig: str) -> str:
    name = sig.split("(")[0]
    return name[0].upper() + name[1:]


B = chr(96)


def render(contract: str, d: str, sigs: list[tuple[str, int]], topics: list[tuple[str, int]]) -> str:
    # Overloads would share a name; v2-core has none.
    names = [ident(s) for s, _ in sigs]
    assert len(set(names)) == len(names), names
    L = [f"-- Generated by scripts/verify/uniswap_v2_core.py. Do not edit.", "",
         f"import Contracts.UniswapV2.{d}.Source",
         "import SolidCore.Refinement.KernelRfl", "import Verify.VC.KernelIdx", "",
         "/-!", f"# SolidCore's checked `{contract}`", "",
         f"The kernel's type check of the Uniswap V2 port's `{contract}` (`contract_ok`), with the checker's",
         "selectors from a table each of whose entries the kernel checks against Keccak-256 once",
         "(`selector_eq`), and its event topics likewise (`digest_eq`).", "-/", "",
         f"namespace SolidCore.Verify.VC.{contract}", "",
         "open SolidCore.Solidity SolidCore.Solidity.Source", "",
         "/-- The interpreter fuel of SolidCore's runs. -/", "def fuel : Nat := 4096", "",
         f"/-- SolidCore's checked `{contract}`. -/",
         "def contract? : Except TypeCheck.TypeError TypeCheck.CheckedContract :=",
         f"  TypeCheck.CheckedInput.contract SolidCore.Verify.VC.Source.{contract}.importedSourceUnit \"{contract}\"", ""]
    for (s, v), n in zip(sigs, names):
        L += [f"/-- The selector of `{s}`. -/", f"abbrev {n[0].lower()+n[1:]}Sel : Nat := {v}", "",
              f"/-- The selector of `{s}`, by Keccak-256 of its signature. -/",
              f"def sel{n} : SolidCore.Solidity.Shared.Word :=",
              f"  SolidCore.Solidity.Source.ABI.selectorFromSignature \"{s}\"", "",
              f"kernel_rfl sel{n}_eq sel{n} {n[0].lower()+n[1:]}Sel", ""]
    L += [f"/-- `ABI.selectorFromSignature`, with `{contract}`'s selectors by table. -/",
          "def selectorTable (s : String) : SolidCore.Solidity.Shared.Word :="]
    for i, ((s, _), n) in enumerate(zip(sigs, names)):
        L.append(f"  {'if' if i == 0 else 'else if'} s = \"{s}\" then {n[0].lower()+n[1:]}Sel")
    L += ["  else SolidCore.Solidity.Source.ABI.selectorFromSignature s", "",
          "theorem selector_eq : SolidCore.Solidity.Source.ABI.selectorFromSignature = selectorTable := by",
          "  funext s", "  unfold selectorTable"]
    for i, ((s, _), n) in enumerate(zip(sigs, names)):
        L += [f"  by_cases h{i} : s = \"{s}\"", f"  · rw [ite_eq_left h{i}, h{i}]",
              f"    exact sel{n}_eq", f"  rw [ite_eq_right h{i}]"]
    L += ["", "/-! ## Event topics, by table -/", ""]
    for s, v in topics:
        n = ident(s)
        L += [f"/-- The topic of {B}{s}{B}. -/", f"abbrev topic{n}Word : Nat := {v:#066x}", "",
              f"/-- The topic of `{s}`, by Keccak-256 of its signature. -/",
              f"def topic{n} : Nat := SolidCore.Solidity.Source.Keccak.digestWord \"{s}\"", "",
              f"kernel_rfl topic{n}_eq topic{n} topic{n}Word", ""]
    L += ["/-- `Keccak.digestWord`, with the contract's event signatures by table. -/",
          "def digestTable (s : String) : Nat :="]
    for i, (s, v) in enumerate(topics):
        L.append(f"  {'if' if i == 0 else 'else if'} s = \"{s}\" then topic{ident(s)}Word")
    L += ["  else SolidCore.Solidity.Source.Keccak.digestWord s", "",
          "theorem digest_eq : SolidCore.Solidity.Source.Keccak.digestWord = digestTable := by",
          "  funext s", "  unfold digestTable"]
    # As SolidCore/Refinement/Solar/Events/Lowering.lean: rewriting the signature into
    # digestWord makes the kernel evaluate Keccak-256 again, subst does not.
    L.append("  split")
    for i, (s, _) in enumerate(topics):
        ind = "  " * (i + 1)
        L.append(f"{ind}· next h => subst h; exact topic{ident(s)}_eq")
        L.append(f"{ind}· split" if i + 1 < len(topics) else f"{ind}· rfl")
    L += ["", "/-- Whether SolidCore type checks the contract. -/",
          "def accepted : Bool :=", "  match contract? with", "  | .ok _ => true", "  | .error _ => false", "",
          "kernel_rfl accepted_eq accepted true using selector_eq SolidCore.Verify.VC.mkIdx_eq", "",
          f"/-- SolidCore type checks the Uniswap V2 port's `{contract}`. -/",
          "theorem contract_ok : ∃ c, contract? = .ok c := by",
          "  have h := accepted_eq", "  unfold accepted at h", "  split at h",
          "  · next c hc => exact ⟨c, hc⟩", "  · simp at h", "",
          f"/-- info: 'SolidCore.Verify.VC.{contract}.contract_ok' depends on axioms: [propext, Classical.choice, Quot.sound] -/",
          "#guard_msgs (whitespace := lax) in", "#print axioms contract_ok", "",
          f"end SolidCore.Verify.VC.{contract}", ""]
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--solc", default="solc")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("contracts", nargs="*")
    a = ap.parse_args()
    status = 0
    for contract, d in CONTRACTS:
        if a.contracts and d not in a.contracts:
            continue
        sol = ROOT / "scripts" / "verify" / "uniswap-v2" / f"{contract}.sol"
        text = render(contract, d, *signatures(a.solc, sol))
        out = ROOT / "Contracts" / "UniswapV2" / d / "Core.lean"
        if a.check:
            if not out.exists() or out.read_text() != text:
                print(f"error: {out.relative_to(ROOT)} is out of date", file=sys.stderr)
                status = 1
        else:
            out.write_text(text)
    return status


if __name__ == "__main__":
    sys.exit(main())

