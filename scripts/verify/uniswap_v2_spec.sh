#!/usr/bin/env bash
# Generate the Lean modules that connect solar-verify's Uniswap V2 ERC20 specs to SolidCore's
# checked UniswapV2ERC20, before their build. They are not committed: they are derived from the
# GPL-3.0 v2-core port (the erased trees of its functions), as Source.lean and Core.lean are.
#
#   scripts/verify/uniswap_v2_spec.sh
#
# Needs scripts/verify/uniswap_v2_gen.sh's outputs (scripts/verify/uniswap-v2/UniswapV2ERC20.sol,
# Contracts/UniswapV2/ERC20/{Source,Core}.lean) and Core's build, and:
#   SOLAR_DIR     a solar checkout with crates/verify/uniswap-v2/{apply_specs.py,uniswap-v2.spec}
#                 and tools/certify/spec_connect.py (nested mapping slots, *_holds_in);
#   SOLAR_VERIFY  its solar-verify binary (--emit-lean-spec);
#   LEAN          the command that runs Lean on one file of this checkout (default: lake env lean).
# Writes, under Contracts/UniswapV2/ERC20/:
#   Spec.lean     solar-verify's --emit-lean-spec export of the ERC20 section of uniswap-v2.spec;
#   SpecMut.lean  the same with transfer's credit clause mutated (old(balanceOf[to]) + value + 1);
#   Connect.lean  spec_connect.py's module: per function the erased tree (kernel_rfl against
#                 SolidCore's checked contract), the spec of the tree (tree_meets_map or
#                 tree_meets_map2) and of SolidCore's contract in every world (_holds_in).
# Fails (exit 1) if any step fails or spec_connect refuses a function: nothing is written as
# passing that does not check.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/../.."
: "${SOLAR_DIR:?set SOLAR_DIR to a solar checkout}"
: "${SOLAR_VERIFY:?set SOLAR_VERIFY to a solar-verify binary}"
# Absolute paths: the steps below run solar-verify from temporary directories.
SOLAR_DIR="$(realpath "$SOLAR_DIR")"
SOLAR_VERIFY="$(realpath "$SOLAR_VERIFY")"
LEAN="${LEAN:-lake env lean}"
FUNCTIONS="${UV2_ERC20_FUNCTIONS:-UniswapV2ERC20.approve,UniswapV2ERC20.transfer}"
sol=scripts/verify/uniswap-v2/UniswapV2ERC20.sol
out=Contracts/UniswapV2/ERC20
for f in "$sol" "$out/Source.lean" "$out/Core.lean"; do
  [[ -s $f ]] || { echo "error: $f missing; run scripts/verify/uniswap_v2_gen.sh" >&2; exit 1; }
done
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
mkdir -p "$tmp/src"; cp "$sol" "$tmp/src/"
# The ERC20 section of the spec file: everything before the Math section.
spec="$SOLAR_DIR/crates/verify/uniswap-v2/uniswap-v2.spec"
awk '/^# -+ Math/ {exit} {print}' "$spec" > "$tmp/erc20.spec"
grep -q '^== contract UniswapV2ERC20' "$tmp/erc20.spec"
# The mutant: transfer credits one more than the amount.
sed 's/^\(@custom:ensures msg.sender != to ==> balanceOf\[to\] == old(balanceOf\[to\]) + value\)$/\1 + 1/' \
  "$tmp/erc20.spec" > "$tmp/erc20-mut.spec"
! cmp -s "$tmp/erc20.spec" "$tmp/erc20-mut.spec" || { echo "error: the mutation did not apply" >&2; exit 1; }
for v in plain mut; do
  s="$tmp/erc20.spec"; [[ $v == mut ]] && s="$tmp/erc20-mut.spec"
  python3 "$SOLAR_DIR/crates/verify/uniswap-v2/apply_specs.py" --src "$tmp/src" --out "$tmp/$v" --spec "$s" >/dev/null
done
(cd "$tmp/plain" && "$SOLAR_VERIFY" UniswapV2ERC20.sol --emit-lean-spec "$tmp/Spec.lean" \
  --lean-spec-module SolidCore.Spec.Export.UniswapV2ERC20)
(cd "$tmp/mut" && "$SOLAR_VERIFY" UniswapV2ERC20.sol --emit-lean-spec "$tmp/SpecMut.lean" \
  --lean-spec-module SolidCore.Spec.Export.UniswapV2ERC20SpecMut)
{ echo "-- Generated by scripts/verify/uniswap_v2_spec.sh. Do not edit."; cat "$tmp/Spec.lean"; } > "$out/Spec.lean"
{ echo "-- Generated by scripts/verify/uniswap_v2_spec.sh. Do not edit."; cat "$tmp/SpecMut.lean"; } > "$out/SpecMut.lean"
# spec_connect.py checks each function against the built Spec and SpecTreeKeccak modules.
lake build ${LAKE_BUILD_FLAGS:--KleanMemory=6000} Contracts.UniswapV2.ERC20.Spec \
  Contracts.UniswapV2.ERC20.SpecTreeKeccak
python3 "$SOLAR_DIR/tools/certify/spec_connect.py" --core-module Contracts.UniswapV2.ERC20.Core \
  --namespace SolidCore.Verify.VC.UniswapV2ERC20 --spec-module Contracts.UniswapV2.ERC20.Spec \
  --bundle SolidCore.Spec.Export.UniswapV2ERC20.UniswapV2ERC20 \
  --module-name SolidCore.Spec.UniswapV2.ERC20 --out "$out/Connect.lean" --lean "$LEAN" \
  --ghost-fixed --only "$FUNCTIONS" \
  --using SolidCore.Verify.VC.UniswapV2ERC20.digest_eq \
  --using SolidCore.Spec.UniswapV2.ERC20.Keccak.keccakWord_eq \
  --import Contracts.UniswapV2.ERC20.SpecTreeKeccak
echo "wrote $out/Spec.lean $out/SpecMut.lean $out/Connect.lean"
