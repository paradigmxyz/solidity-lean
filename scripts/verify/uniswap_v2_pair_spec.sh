#!/usr/bin/env bash
# Generate the inputs of UniswapV2Pair's published statement (Contracts/UniswapV2/PairSpec), before
# its build. None is committed: each is derived from the GPL-3.0 v2-core port.
#
#   scripts/verify/uniswap_v2_pair_spec.sh
#
# Needs scripts/verify/uniswap_v2_gen.sh's outputs (scripts/verify/uniswap-v2/UniswapV2Pair.sol and
# Contracts/UniswapV2/Pair/{Source,Core}.lean), and:
#   SOLAR_DIR     a solar checkout with crates/verify/uniswap-v2/{apply_specs.py,uniswap-v2.spec};
#   SOLAR         its solar binary (the bytecode and its stage export);
#   SOLAR_VERIFY  its solar-verify binary (--emit-lean-spec, with dynamic parameters exported as
#                 their head word: solar's spec_lean.rs with the pair-spec lane's patch).
# Writes, under Contracts/UniswapV2/PairSpec/:
#   Spec.lean       solar-verify's --emit-lean-spec export of the ERC20 and Pair sections of
#                   uniswap-v2.spec, applied to the flattened UniswapV2Pair.sol;
#   SpecWrongK.lean the same with swap's fee-adjusted constant-product clause mutated (fee 4/1000
#                   instead of 3/1000, stronger than the code meets): a negative control;
#   Bytecode.lean   solar -Zemit-lean-stages's Bytecode.lean for UniswapV2Pair (the export);
#   Runtime.lean    the runtime bytecode of solar's plain compile (--emit=bin-runtime), as numbers,
#                   the bytes the statement binds the export to;
#   SourceNoUpdate.lean, RuntimeNoUpdate.lean, SourceSkimUpdate.lean, RuntimeSkimUpdate.lean
#                   swap without its _update and skim that updates the reserves (negative controls
#                   Negative.lean runs): SolidCore's translation and solar's compile of the mutant
#                   (scripts/verify/uniswap-v2/UniswapV2PairNoUpdate.sol, UniswapV2PairSkimUpdate.sol).
# Fails (exit 1) if any step fails; nothing is written as passing that does not check.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/../.."
: "${SOLAR_DIR:?set SOLAR_DIR to a solar checkout}"
: "${SOLAR:?set SOLAR to a solar binary}"
: "${SOLAR_VERIFY:?set SOLAR_VERIFY to a solar-verify binary}"
sol=scripts/verify/uniswap-v2/UniswapV2Pair.sol
out=Contracts/UniswapV2/PairSpec
[[ -s $sol ]] || { echo "error: $sol missing; run scripts/verify/uniswap_v2_gen.sh" >&2; exit 1; }
opts=(-Ogas --evm-version osaka)
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
mkdir -p "$tmp/src"; cp "$sol" "$tmp/src/"
# The ERC20 and Pair sections (the flattened file holds both contracts; Math and Factory are not in it).
awk '/^# -+ Factory/ {exit} /^# -+ Math/ {skip=1} /^# -+ Pair/ {skip=0} !skip' \
  "$SOLAR_DIR/crates/verify/uniswap-v2/uniswap-v2.spec" > "$tmp/pair.spec"
grep -q '^== contract UniswapV2Pair' "$tmp/pair.spec"
grep -q '^== function UniswapV2Pair.swap' "$tmp/pair.spec"
# The wrong-K mutant: swap's fee-adjusted clause with 4 instead of 3 (stronger than the code meets).
sed 's/^\(@custom:ensures (reserve0 \* 1000 - IN(reserve0, amount0Out) \* \)3\() \* (reserve1 \* 1000 - IN(reserve1, amount1Out) \* \)3/\14\24/' \
  "$tmp/pair.spec" > "$tmp/pair-wrongk.spec"
! cmp -s "$tmp/pair.spec" "$tmp/pair-wrongk.spec" || { echo "error: the wrong-K mutation did not apply" >&2; exit 1; }
for v in plain wrongk; do
  s="$tmp/pair.spec"; [[ $v == wrongk ]] && s="$tmp/pair-wrongk.spec"
  python3 "$SOLAR_DIR/crates/verify/uniswap-v2/apply_specs.py" --src "$tmp/src" --out "$tmp/$v" --spec "$s" >/dev/null
done
(cd "$tmp/plain" && "$SOLAR_VERIFY" UniswapV2Pair.sol --emit-lean-spec "$tmp/Spec.lean" \
  --lean-spec-module SolidCore.Spec.Export.UniswapV2Pair)
(cd "$tmp/wrongk" && "$SOLAR_VERIFY" UniswapV2Pair.sol --emit-lean-spec "$tmp/SpecWrongK.lean" \
  --lean-spec-module SolidCore.Spec.Export.UniswapV2PairWrongK)
for m in Spec SpecWrongK; do
  { echo "-- Generated by scripts/verify/uniswap_v2_pair_spec.sh. Do not edit."; cat "$tmp/$m.lean"; } > "$out/$m.lean"
done
# The bytecode: the stage export and the plain compile, from the same solar.
(cd "$tmp/src" && "$SOLAR" UniswapV2Pair.sol "${opts[@]}" --emit=bin-runtime -Zemit-lean-stages="$tmp/gen" >/dev/null 2>"$tmp/gen.log") \
  || { cat "$tmp/gen.log" >&2; exit 1; }
[[ -s "$tmp/gen/UniswapV2Pair/Bytecode.lean" ]] || { echo "error: no Bytecode.lean in the export" >&2; exit 1; }
{ echo "-- Generated by scripts/verify/uniswap_v2_pair_spec.sh from solar -Zemit-lean-stages. Do not edit."
  cat "$tmp/gen/UniswapV2Pair/Bytecode.lean"; } > "$out/Bytecode.lean"
hex=$(cd "$tmp/src" && "$SOLAR" UniswapV2Pair.sol "${opts[@]}" --emit=bin-runtime 2>/dev/null \
  | python3 -c 'import json,sys; print(json.load(sys.stdin)["contracts"]["UniswapV2Pair.sol:UniswapV2Pair"]["bin-runtime"])')
[[ $hex =~ ^[0-9a-f]+$ ]] || { echo "error: no runtime bytecode for UniswapV2Pair" >&2; exit 1; }
python3 - "$hex" > "$out/Runtime.lean" <<'PY'
import sys
b = bytes.fromhex(sys.argv[1])
rows = [", ".join(hex(x) for x in b[i:i + 16]) for i in range(0, len(b), 16)]
print("-- Generated by scripts/verify/uniswap_v2_pair_spec.sh from solar --emit=bin-runtime. Do not edit.")
print()
print("namespace SolidCore.Spec.UniswapV2.PairSpec")
print()
print("/-- The runtime bytecode of UniswapV2Pair, from solar's plain compile, as numbers. -/")
print("def runtimeBytes : List Nat :=")
print("  [" + ",\n   ".join(rows) + "]")
print()
print("end SolidCore.Spec.UniswapV2.PairSpec")
PY
echo "wrote $out/Spec.lean $out/SpecWrongK.lean $out/Bytecode.lean $out/Runtime.lean (${#hex} hex digits)"


# Negative controls by execution: swap without its reserve update (the mutant source, its SolidCore
# translation and solar's compile of it).
python3 - "$sol" "$tmp/src/UniswapV2PairNoUpdate.sol" <<'PY'
import sys
src = open(sys.argv[1]).read()
at = src.index("external lock {", src.index("function swap(uint amount0Out, uint amount1Out, address to, bytes calldata data) external lock"))
line = "        _update(balance0, balance1, _reserve0, _reserve1);\n"
i = src.index(line, at)
nxt = src.find("function ", at + 1)
assert nxt == -1 or i < nxt, "swap's _update not found in swap"
open(sys.argv[2], "w").write(src[:i] + src[i + len(line):])
PY
mut=scripts/verify/uniswap-v2/UniswapV2PairNoUpdate.sol
cp "$tmp/src/UniswapV2PairNoUpdate.sol" "$mut"
solc="${SOLC:-.cache/solc-0.8.35}"
{ echo "-- Generated by scripts/verify/uniswap_v2_pair_spec.sh: swap without its _update. Do not edit."
  echo; echo "import SolidCore.Solidity.Checked"; echo; echo "open SolidCore.Solidity"
  python3 scripts/solc_ast_to_lean_source.py --solc "$solc" --contract UniswapV2Pair \
    --namespace SolidCore.Verify.VC.Source.UniswapV2PairNoUpdate "$mut" \
    | tail -n +3; } > "$out/SourceNoUpdate.lean"
grep -q 'importedSourceUnit' "$out/SourceNoUpdate.lean" || { echo "error: no mutant source" >&2; exit 1; }
hexmut=$(cd "$tmp/src" && "$SOLAR" UniswapV2PairNoUpdate.sol "${opts[@]}" --emit=bin-runtime 2>/dev/null \
  | python3 -c 'import json,sys; print(json.load(sys.stdin)["contracts"]["UniswapV2PairNoUpdate.sol:UniswapV2Pair"]["bin-runtime"])')
[[ $hexmut =~ ^[0-9a-f]+$ && $hexmut != "$hex" ]] || { echo "error: no distinct mutant bytecode" >&2; exit 1; }
python3 - "$hexmut" > "$out/RuntimeNoUpdate.lean" <<'PY'
import sys
b = bytes.fromhex(sys.argv[1])
rows = [", ".join(hex(x) for x in b[i:i + 16]) for i in range(0, len(b), 16)]
print("-- Generated by scripts/verify/uniswap_v2_pair_spec.sh: solar's compile of swap without its _update. Do not edit.")
print()
print("namespace SolidCore.Spec.UniswapV2.PairSpec")
print()
print("/-- The runtime bytecode of the mutant (swap without its reserve update), as numbers. -/")
print("def runtimeNoUpdate : List Nat :=")
print("  [" + ",\n   ".join(rows) + "]")
print()
print("end SolidCore.Spec.UniswapV2.PairSpec")
PY
echo "wrote $out/SourceNoUpdate.lean $out/RuntimeNoUpdate.lean (${#hexmut} hex digits)"

# Second mutant: skim that first forces the reserves to the balances (sync's _update at its start).
python3 - "$sol" "$tmp/src/UniswapV2PairSkimUpdate.sol" <<'PY'
import sys
src = open(sys.argv[1]).read()
head = "function skim(address to) external lock {\n"
i = src.index(head) + len(head)
assert src.count(head) == 1, "skim's body not found once"
upd = "        _update(IERC20(token0).balanceOf(address(this)), IERC20(token1).balanceOf(address(this)), reserve0, reserve1);\n"
open(sys.argv[2], "w").write(src[:i] + upd + src[i:])
PY
mut2=scripts/verify/uniswap-v2/UniswapV2PairSkimUpdate.sol
cp "$tmp/src/UniswapV2PairSkimUpdate.sol" "$mut2"
{ echo "-- Generated by scripts/verify/uniswap_v2_pair_spec.sh: skim that updates the reserves. Do not edit."
  echo; echo "import SolidCore.Solidity.Checked"; echo; echo "open SolidCore.Solidity"
  python3 scripts/solc_ast_to_lean_source.py --solc "$solc" --contract UniswapV2Pair \
    --namespace SolidCore.Verify.VC.Source.UniswapV2PairSkimUpdate "$mut2" \
    | tail -n +3; } > "$out/SourceSkimUpdate.lean"
grep -q 'importedSourceUnit' "$out/SourceSkimUpdate.lean" || { echo "error: no skim mutant source" >&2; exit 1; }
hexmut2=$(cd "$tmp/src" && "$SOLAR" UniswapV2PairSkimUpdate.sol "${opts[@]}" --emit=bin-runtime 2>/dev/null \
  | python3 -c 'import json,sys; print(json.load(sys.stdin)["contracts"]["UniswapV2PairSkimUpdate.sol:UniswapV2Pair"]["bin-runtime"])')
[[ $hexmut2 =~ ^[0-9a-f]+$ && $hexmut2 != "$hex" ]] || { echo "error: no distinct skim mutant bytecode" >&2; exit 1; }
python3 - "$hexmut2" > "$out/RuntimeSkimUpdate.lean" <<'PY'
import sys
b = bytes.fromhex(sys.argv[1])
rows = [", ".join(hex(x) for x in b[i:i + 16]) for i in range(0, len(b), 16)]
print("-- Generated by scripts/verify/uniswap_v2_pair_spec.sh: solar's compile of skim that updates the reserves. Do not edit.")
print()
print("namespace SolidCore.Spec.UniswapV2.PairSpec")
print()
print("/-- The runtime bytecode of the mutant (skim forcing the reserves to the balances), as numbers. -/")
print("def runtimeSkimUpdate : List Nat :=")
print("  [" + ",\n   ".join(rows) + "]")
print()
print("end SolidCore.Spec.UniswapV2.PairSpec")
PY
echo "wrote $out/SourceSkimUpdate.lean $out/RuntimeSkimUpdate.lean (${#hexmut2} hex digits)"
