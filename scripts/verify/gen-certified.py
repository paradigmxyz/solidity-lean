#!/usr/bin/env python3
"""Write Lean modules that discharge a solar-verify --dump-lean script in the kernel along
certificates (Verify/VC/Cert.lean).

Usage: gen-certified.py MODULE NAMESPACE IMPORT SCRIPT COUNT CERTDIR [--chunk K]
           [--reject IMPORT SCRIPT INDEX]...

CERTDIR holds ob<i>.txt, "<d> <certificate>" as scripts/verify/certs.lean writes them (the
compiled search, not trusted). Writes MODULE.Part<k>, one theorem per obligation
(dischargeAtC SCRIPT i d cert = true, by decide +kernel), and MODULE: the count of obligations and
script_valid : Valid SCRIPT from dischargeScript_of_certs. Without a certificate for every
obligation, MODULE proves only the obligations it has and lists the rest; no script_valid.
Each --reject names a mutant script and an obligation the plain discharge rejects there.
"""
import os
import sys

HEADER = "set_option maxRecDepth 100000"


def write(module, lines):
    path = module.replace(".", "/") + ".lean"
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write("\n".join(lines))


def main(argv):
    module, ns, imp, script, count, certdir = argv[:6]
    count = int(count)
    chunk = 2
    rejects = []
    rest = argv[6:]
    while rest:
        if rest[0] == "--chunk":
            chunk = int(rest[1]); rest = rest[2:]
        elif rest[0] == "--reject":
            rejects.append((rest[1], rest[2], int(rest[3]))); rest = rest[4:]
        else:
            sys.exit(f"unknown argument {rest[0]}")
    certs = {}
    for i in range(count):
        p = os.path.join(certdir, f"ob{i}.txt")
        if os.path.exists(p):
            d, c = open(p).read().strip().split(" ", 1)
            certs[i] = (d, c)
    have = sorted(certs)
    missing = [i for i in range(count) if i not in certs]
    parts = []
    for k, lo in enumerate(range(0, len(have), chunk)):
        part = f"{module}.Part{k}"
        parts.append(part)
        idx = have[lo:lo + chunk]
        L = ["import Verify.VC.Cert", f"import {imp}", "",
             f"/-! Obligations {', '.join(map(str, idx))} of `{script}`, each checked by the kernel along",
             "its certificate (generated by scripts/verify/gen-certified.py). -/", "",
             f"namespace {ns}", "", "open SolidCore.Verify.VC", "", HEADER, ""]
        for i in idx:
            d, c = certs[i]
            L += [f"def cert_{i} : Cert := {c}", "",
                  f"theorem ob_{i} : dischargeAtC {script} {i} {d} cert_{i} = true := by decide +kernel", ""]
        L += [f"end {ns}", ""]
        write(part, L)
    seen = []
    for i in parts + [r[0] for r in rejects]:
        if i not in seen:
            seen.append(i)
    L = ["import Verify.VC.Discharge"] + [f"import {i}" for i in seen]
    L += ["", "/-!", f"# `{script}`, discharged by the kernel along certificates", "",
          "Generated by scripts/verify/gen-certified.py: one kernel check of `dischargeAtC` per",
          "obligation (the Part modules), and the script's verdict `Valid` from them, with no solver.",
          "-/", "", f"namespace {ns}", "", "open SolidCore.Verify.VC", "", HEADER, "",
          f"theorem obligation_count : (obligations {script}).length = {count} := by decide +kernel", ""]
    if not missing:
        L += ["/-- Every obligation of the script has no model. -/",
              f"theorem script_valid : Valid {script} :=",
              "  dischargeScript_of_certs _ fun i hi =>",
              "    match i, obligation_count \u25b8 hi with"]
        L += [f"    | {i}, _ => \u27e8_, _, ob_{i}\u27e9" for i in range(count)]
        L += [f"    | _ + {count}, h => absurd h (by omega)", ""]
    else:
        L += [f"/-- The obligations checked so far; {', '.join(map(str, missing))} have no certificate. -/",
              "theorem checked : " + " \u2227 ".join(f"(\u2203 d c, dischargeAtC {script} {i} d c = true)" for i in have) + " :=",
              "  \u27e8" + ", ".join(f"\u27e8_, _, ob_{i}\u27e9" for i in have) + "\u27e9", ""]
    for k, (_, m, idx) in enumerate(rejects):
        L += [f"/-- The mutant script is rejected at obligation {idx}. -/",
              f"theorem reject_{k} : dischargeScript {m} = false :=",
              f"  dischargeScript_false_of (i := {idx}) (by decide +kernel) (by decide +kernel)", ""]
    if not missing:
        L += [f"/-- info: '{ns}.script_valid' depends on axioms: [propext, Classical.choice, Quot.sound] -/",
              "#guard_msgs (whitespace := lax) in", "#print axioms script_valid", ""]
    L += [f"end {ns}", ""]
    write(module, L)


if __name__ == "__main__":
    main(sys.argv[1:])
