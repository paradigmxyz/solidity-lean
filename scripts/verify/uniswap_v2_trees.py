#!/usr/bin/env python3
"""Writes Contracts/UniswapV2/ERC20/Nested/Trees.lean: the generic source stage's erased trees of
UniswapV2ERC20's approve and transferFrom, checked by the kernel against SolidCore's checked contract.

    scripts/verify/uniswap_v2_trees.py [--lean 'lake env lean']

Needs scripts/verify/uniswap_v2_gen.sh's outputs and the build of Contracts.UniswapV2.ERC20.Core and
Contracts.UniswapV2.ERC20.SpecTreeKeccak. The module is not committed (the trees are derived from the
GPL-3.0 v2-core port, as Source.lean and Core.lean are). Lean prints each tree by evaluation; the
module then states it by kernel_rfl, so nothing printed here is trusted: a wrong tree fails the build.
Exit 1 when the probe fails or a function is outside the generic source stage.
"""

import argparse
import pathlib
import shlex
import subprocess
import sys
import tempfile

NS = "SolidCore.Verify.VC.UniswapV2ERC20"
FNS = [("approve", 157198259), ("transferFrom", 599290589)]
USINGS = " ".join([
    f"{NS}.selector_eq", "SolidCore.Verify.VC.mkIdx_eq", f"{NS}.digest_eq",
    "SolidCore.Spec.UniswapV2.ERC20.Keccak.keccakWord_eq",
])
BT = chr(96)

PROBE = """import Contracts.UniswapV2.ERC20.Core
import Verify.VC.Model

open SolidCore.Refinement SolidCore.Refinement.Generic SolidCore.Solidity

#eval show IO Unit from do
  match {ns}.contract? with
  | .error _ => IO.println "TREES error the contract does not type check"
  | .ok c =>
    let dep := match TypeCheck.CheckedContract.constructWithContext? {ns}.fuel c (Wide.ctxOf c)
        Source.State.empty SolidCore.Refinement.selfAddress 0 [] with
      | some (Source.CallResult.returned d _) =>
        if d.events.isEmpty then some d.storage.toList else none
      | _ => none
    IO.println s!"TREES deployed {{repr dep}}"
    for sel in {sels} do
      match (c.core.findFunctionBySelector? sel).map fun f => (f.params.length, eraseFn (envOf c.core) {ns}.fuel f) with
      | none => IO.println s!"TREES fn {{sel}} none"
      | some (n, none) => IO.println s!"TREES fn {{sel}} {{n}} noerase"
      | some (n, some t) => IO.println s!"TREES fn {{sel}} {{n}} TREE {{(repr t).pretty 100000}}"
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--lean", default="lake env lean")
    ap.add_argument("--out", type=pathlib.Path, default=pathlib.Path("Contracts/UniswapV2/ERC20/Nested/Trees.lean"))
    args = ap.parse_args()
    probe = PROBE.format(ns=NS, sels="[" + ", ".join(str(s) for _, s in FNS) + "]")
    with tempfile.NamedTemporaryFile("w", suffix=".lean", dir=".", delete=False) as f:
        f.write(probe)
        path = pathlib.Path(f.name)
    try:
        res = subprocess.run(shlex.split(args.lean) + [str(path)], capture_output=True, text=True, check=False)
    finally:
        path.unlink()
    lines = [l[len("TREES "):] for l in res.stdout.splitlines() if l.startswith("TREES ")]
    if res.returncode != 0 or not lines or lines[0].startswith("error"):
        sys.exit(f"uniswap_v2_trees: the probe failed:\n{res.stdout}\n{res.stderr}")
    if not lines[0].startswith("deployed some "):
        sys.exit(f"uniswap_v2_trees: the constructor does not deploy without logs: {lines[0]}")
    deployed = lines[0][len("deployed some "):]
    out = [
        "-- Generated by scripts/verify/uniswap_v2_trees.py. Do not edit.",
        "import Contracts.UniswapV2.ERC20.Core",
        "import Contracts.UniswapV2.ERC20.SpecTreeKeccak",
        "import Verify.VC.Model",
        "import Verify.VC.KernelIdx",
        "import SolidCore.Refinement.KernelRfl",
        "",
        "/-!",
        "# UniswapV2ERC20's approve and transferFrom as the generic source stage erases them",
        "",
        f"{BT}deploy_eq{BT}: the constructor deploys with {BT}deployed{BT} and no logs. {BT}F_erase_eq{BT}: SolidCore's",
        f"checked contract dispatches F's selector to a function the generic source stage erases to {BT}F_tree{BT}.",
        f"Both by {BT}kernel_rfl{BT} from the source text up.",
        "-/",
        "",
        "namespace SolidCore.Spec.UniswapV2.ERC20.Nested",
        "",
        "open SolidCore.Refinement SolidCore.Refinement.Generic",
        "",
        f"def deployed : List (Nat × Nat) := {deployed}",
        "",
        "def deploy? : Bool :=",
        f"  match {NS}.contract? with",
        f"  | .ok c => Wide.deployedAt {NS}.fuel c deployed",
        "  | .error _ => false",
        "",
        f"kernel_rfl deploy_eq deploy? true using {USINGS}",
        "",
    ]
    for (name, sel), line in zip(FNS, lines[1:]):
        parts = line.split(" ", 4)
        if parts[1] != str(sel) or parts[2] == "none" or parts[3] == "noerase":
            sys.exit(f"uniswap_v2_trees: {name} is not erased: {line[:200]}")
        n, tree = int(parts[2]), parts[4].removeprefix("TREE ")
        out += [
            f"/-- {BT}{name}{BT} as the stage's ABI sees it. -/",
            f"def fn_{name} : SolidCore.Refinement.Abi.Fn := ⟨{sel}, List.replicate {n} (.uint 256)⟩",
            "",
            f"def {name}_tree : Tree :=",
            f"  {tree}",
            "",
            f"def {name}_erase? : Option (Nat × Option Tree) :=",
            f"  match {NS}.contract? with",
            f"  | .ok c => (c.core.findFunctionBySelector? {sel}).map fun f => (f.params.length, eraseFn (envOf c.core) {NS}.fuel f)",
            "  | .error _ => none",
            "",
            f"kernel_rfl {name}_erase_eq {name}_erase? (some ({n}, some {name}_tree)) using {USINGS}",
            "",
        ]
    out += ["end SolidCore.Spec.UniswapV2.ERC20.Nested", ""]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(out))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
