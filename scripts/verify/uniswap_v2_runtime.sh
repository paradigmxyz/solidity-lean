#!/usr/bin/env bash
# Write Contracts/UniswapV2/ERC20/Runtime.lean: UniswapV2ERC20's runtime bytecode as solar emits it
# for the certification target's options (-Ogas --evm-version osaka), from the ^0.8 port.
# Generated at build time and not committed (the port and its bytecode derive from GPL-3.0 v2-core).
#
#   SOLAR=/path/to/solar scripts/verify/uniswap_v2_runtime.sh [PORT_DIR]
#
# PORT_DIR defaults to .cache/uniswap-v2/src (scripts/verify/uniswap_v2_gen.sh writes it).
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/../.."

: "${SOLAR:?set SOLAR to the solar binary whose output is certified}"
port="${1:-.cache/uniswap-v2/src}"
src="$port/UniswapV2ERC20.sol"
[[ -s "$src" ]] || { echo "error: $src missing (run scripts/verify/uniswap_v2_gen.sh)" >&2; exit 1; }

version="$("$SOLAR" --version)" || { echo "error: $SOLAR --version failed" >&2; exit 1; }
version="$(head -n1 <<<"$version") ($(grep -m1 "Commit SHA" <<<"$version" || echo "no commit"))"
json="$(cd "$port" && "$SOLAR" -Ogas --evm-version osaka --emit bin-runtime UniswapV2ERC20.sol 2>/dev/null)" \
  || { echo "error: solar failed on $src" >&2; exit 1; }
hex="$(jq -er '.contracts["UniswapV2ERC20.sol:UniswapV2ERC20"]["bin-runtime"]' <<<"$json")" \
  || { echo "error: no runtime bytecode for UniswapV2ERC20" >&2; exit 1; }
[[ "$hex" =~ ^([0-9a-f]{2})+$ ]] || { echo "error: runtime bytecode is not even-length hex" >&2; exit 1; }
digest="$(printf '%s' "$hex" | sha256sum | cut -d' ' -f1)"
srcdigest="$(sha256sum "$src" | cut -d' ' -f1)"

out=Contracts/UniswapV2/ERC20/Runtime.lean
{
  echo "-- Generated by scripts/verify/uniswap_v2_runtime.sh; do not edit, do not commit."
  echo "-- solar: $version"
  echo "-- options: -Ogas --evm-version osaka --emit bin-runtime"
  echo "-- source sha256: $srcdigest"
  echo "-- runtime hex sha256: $digest ($(( ${#hex} / 2 )) bytes)"
  echo
  echo "namespace SolidCore.Spec.UniswapV2.ERC20.Runtime"
  echo
  echo "/-- UniswapV2ERC20's runtime bytecode, as the solar above emits it. -/"
  printf 'def code : ByteArray := ⟨#['
  sed -E 's/(..)/0x\1, /g; s/, $//' <<<"$hex"
  echo "]⟩"
  echo
  echo "end SolidCore.Spec.UniswapV2.ERC20.Runtime"
} > "$out.tmp"
mv "$out.tmp" "$out"
echo "wrote $out: $(( ${#hex} / 2 )) bytes, sha256 $digest"
