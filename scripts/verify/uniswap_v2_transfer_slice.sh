#!/usr/bin/env bash
# Generate the Lean modules of UniswapV2ERC20.transfer's certified slice that depend on the
# GPL-3.0 v2-core port, before their build (not committed, like Source.lean and Core.lean):
#
#   scripts/verify/uniswap_v2_transfer_slice.sh
#
# Needs scripts/verify/uniswap_v2_gen.sh's outputs (scripts/verify/uniswap-v2/UniswapV2ERC20.sol,
# Contracts/UniswapV2/ERC20/{Source,Core}.lean) and:
#   SOLAR_DIR     a solar checkout with crates/verify/uniswap-v2/{apply_specs.py,transfer-slice.spec}
#                 and tools/certify/spec_connect.py with --tree-only;
#   SOLAR_VERIFY  its solar-verify binary (--emit-lean-spec);
#   SOLC          solc 0.8.35 (default .cache/solc-0.8.35, which uniswap_v2_gen.sh downloads);
#   LEAN          the command that runs Lean on one file of this checkout (default: lake env lean).
# Writes, under Contracts/UniswapV2/ERC20/Slice/Gen/:
#   Spec.lean          solar-verify's --emit-lean-spec export of transfer-slice.spec;
#   Tree.lean          spec_connect.py --tree-only: transfer's erased tree, checked against
#                      SolidCore's contract by kernel_rfl (transfer_erase_eq, deploy_eq);
#   Mut<M>/Source.lean, Mut<M>/Core.lean, Mut<M>/Tree.lean
#                      the frontend's source and the checked contract of each source mutant of the
#                      port (scripts/verify/uniswap-v2/transfer-mutants.txt): one text edit of
#                      the port, which must apply exactly once; Tree.lean is the mutant's transfer
#                      erased by the same stage (spec_connect.py --tree-only).
# Fails (exit 1) if any step fails: nothing is written as passing that does not check.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/../.."
: "${SOLAR_DIR:?set SOLAR_DIR to a solar checkout}"
: "${SOLAR_VERIFY:?set SOLAR_VERIFY to a solar-verify binary}"
SOLAR_DIR="$(realpath "$SOLAR_DIR")"
SOLAR_VERIFY="$(realpath "$SOLAR_VERIFY")"
SOLC="${SOLC:-.cache/solc-0.8.35}"
LEAN="${LEAN:-lake env lean}"
sol=scripts/verify/uniswap-v2/UniswapV2ERC20.sol
out=Contracts/UniswapV2/ERC20/Slice/Gen
for f in "$sol" Contracts/UniswapV2/ERC20/Source.lean Contracts/UniswapV2/ERC20/Core.lean; do
  [[ -s $f ]] || { echo "error: $f missing; run scripts/verify/uniswap_v2_gen.sh" >&2; exit 1; }
done
mkdir -p "$out"
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
mkdir -p "$tmp/src"; cp "$sol" "$tmp/src/"
spec="$SOLAR_DIR/crates/verify/uniswap-v2/transfer-slice.spec"
python3 "$SOLAR_DIR/crates/verify/uniswap-v2/apply_specs.py" --src "$tmp/src" --out "$tmp/plain" --spec "$spec" >/dev/null
(cd "$tmp/plain" && "$SOLAR_VERIFY" UniswapV2ERC20.sol --emit-lean-spec "$tmp/Spec.lean" \
  --lean-spec-module SolidCore.Spec.Export.UniswapV2ERC20Slice)
{ echo "-- Generated by scripts/verify/uniswap_v2_transfer_slice.sh. Do not edit."; cat "$tmp/Spec.lean"; } > "$out/Spec.lean"

# The source mutants: NAME, then the exact text of the port and its replacement, tab-separated.
while IFS=$'\t' read -r name old new; do
  [[ -z $name || $name == \#* ]] && continue
  old="${old//\\n/$'\n'}"; new="${new//\\n/$'\n'}"
  msol="scripts/verify/uniswap-v2/UniswapV2ERC20Mut$name.sol"
  python3 - "$sol" "$msol" "$old" "$new" <<'PY'
import sys
src, dst, old, new = sys.argv[1:]
text = open(src).read()
if text.count(old) != 1:
    sys.exit(f"error: mutant edit applies {text.count(old)} times, not once: {old!r}")
open(dst, "w").write(text.replace(old, new))
PY
  d="$out/Mut$name"; mkdir -p "$d"
  python3 scripts/verify/uniswap_v2_mutant.py --solc "$SOLC" --sol "$msol" --name "$name" --out "$d"
done < scripts/verify/uniswap-v2/transfer-mutants.txt

lake build ${LAKE_BUILD_FLAGS:--KleanMemory=6000} Contracts.UniswapV2.ERC20.Slice.Gen.Spec \
  Contracts.UniswapV2.ERC20.SpecTreeKeccak Verify.VC.Model Verify.Spec.Tree Verify.Spec.TreeMap \
  Verify.Spec.TreeMapNested Verify.Spec.TreeIn Verify.VC.KernelIdx
python3 "$SOLAR_DIR/tools/certify/spec_connect.py" --core-module Contracts.UniswapV2.ERC20.Core \
  --namespace SolidCore.Verify.VC.UniswapV2ERC20 --spec-module Contracts.UniswapV2.ERC20.Slice.Gen.Spec \
  --bundle SolidCore.Spec.Export.UniswapV2ERC20Slice.UniswapV2ERC20 \
  --module-name SolidCore.Spec.UniswapV2.ERC20.Slice.Gen --out "$out/Tree.lean" --lean "$LEAN" \
  --tree-only --only UniswapV2ERC20.transfer \
  --using SolidCore.Verify.VC.UniswapV2ERC20.digest_eq \
  --using SolidCore.Spec.UniswapV2.ERC20.Keccak.keccakWord_eq \
  --import Contracts.UniswapV2.ERC20.SpecTreeKeccak

# Each mutant's transfer, erased by the same stage and checked against its own contract.
while IFS=$'\t' read -r name _ _; do
  [[ -z $name || $name == \#* ]] && continue
  lake build ${LAKE_BUILD_FLAGS:--KleanMemory=6000} Contracts.UniswapV2.ERC20.Slice.Gen.Mut$name.Core
  python3 "$SOLAR_DIR/tools/certify/spec_connect.py" --core-module Contracts.UniswapV2.ERC20.Slice.Gen.Mut$name.Core \
    --namespace SolidCore.Verify.VC.UniswapV2ERC20Mut$name --spec-module Contracts.UniswapV2.ERC20.Slice.Gen.Spec \
    --bundle SolidCore.Spec.Export.UniswapV2ERC20Slice.UniswapV2ERC20 \
    --module-name SolidCore.Spec.UniswapV2.ERC20.Slice.Gen.Mut$name --out "$out/Mut$name/Tree.lean" --lean "$LEAN" \
    --tree-only --only UniswapV2ERC20.transfer \
    --using SolidCore.Verify.VC.UniswapV2ERC20Mut$name.digest_eq \
    --using SolidCore.Spec.UniswapV2.ERC20.Keccak.keccakWord_eq \
    --import Contracts.UniswapV2.ERC20.SpecTreeKeccak
done < scripts/verify/uniswap-v2/transfer-mutants.txt
echo "wrote $out"
